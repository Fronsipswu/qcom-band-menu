def translate(path, pairs):
    with io.open(path, "r", encoding="utf-8") as f:
        s = f.read()
    orig = s
    for old, new in pairs:
        if old in s:
            s = s.replace(old, new)
        else:
            print("  !! NOT FOUND in {}: {!r}".format(os.path.basename(path), old[:60]))
    if s != orig:
        with io.open(path, "w", encoding="utf-8") as f:
            f.write(s)
        print("  updated {}".format(path))

print("Applying global replacements...")
for root, dirs, files in os.walk(BASE):
    for fn in files:
        if fn.endswith(".kt"):
            translate(os.path.join(root, fn), GLOBAL)

print("Applying file-specific replacements...")
for rel, pairs in FILES.items():
    p = os.path.join(BASE, rel)
    if os.path.exists(p):
        translate(p, pairs)
    else:
        print("  !! MISSING FILE:", p)

print("Done.")