#!/usr/bin/env python3
"""Generates the Android string resources from i18n/strings.txt.

    python i18n/gen_strings.py            write the res/values* files
    python i18n/gen_strings.py --check    fail if they are out of date (for CI)

Only the standard library is needed. Errors name the line in strings.txt.
"""
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "strings.txt"
RES = HERE.parent / "app" / "src" / "main" / "res"
MARK = "Generated by i18n/gen_strings.py"

# Language code -> Android resource folder suffix. Codes not listed here use
# the code itself (de -> values-de, ru -> values-ru). English is the default.
# Add a line only for a script or region code: zh-TW -> zh-rTW, and a script
# such as Hans -> b+zh+Hans (Android's form for those).
QUALIFIER = {"en": "", "zh": "b+zh+Hans"}
# Keys that must exist for a language to be offered in the app's Language list.
LANGUAGE_KEY = "language.name"

ENTRY = re.compile(r"^\[([a-z0-9_.]+)\]$")
LINE = re.compile(r"^([a-z]{2,3}(?:-[A-Za-z0-9]+)?)\s*=\s*(.+)$")
PLACEHOLDER = re.compile(r"\{([a-z_]+)\}")


def fail(msg):
    print(f"strings.txt: {msg}", file=sys.stderr)
    sys.exit(1)


def parse(text):
    """Returns {key: {lang: value}} in file order, validated."""
    entries = {}
    key = None
    for number, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        where = f"line {number}"
        if m := ENTRY.match(line):
            key = m.group(1)
            if key in entries:
                fail(f"{where}: duplicate key [{key}]")
            entries[key] = {}
        elif m := LINE.match(line):
            if key is None:
                fail(f"{where}: a language line must come after a [key]")
            lang, value = m.group(1), m.group(2).strip()
            if lang in entries[key]:
                fail(f"{where}: [{key}] has {lang} twice")
            entries[key][lang] = value
        else:
            fail(f"{where}: expected [key] or 'code = text', got: {line}")
    for key, langs in entries.items():
        if "en" not in langs:
            fail(f"[{key}] has no en line")
        english = placeholders(langs["en"])
        for lang, value in langs.items():
            if set(placeholders(value)) != set(english):
                fail(f"[{key}] {lang}: placeholders {placeholders(value)} "
                     f"do not match English {english}")
    return entries


def placeholders(value):
    """Names in order of first appearance, without repeats."""
    names = []
    for name in PLACEHOLDER.findall(value):
        if name not in names:
            names.append(name)
    return names


def android_text(value, english):
    """The string as Android stores it: {name} becomes %n$s, literal % is %%,
    and XML and quote characters are escaped."""
    text = value.replace("%", "%%")
    for name in PLACEHOLDER.findall(text):
        text = text.replace("{" + name + "}", f"%{english.index(name) + 1}$s")
    text = escape(text).replace("'", "\\'").replace('"', '\\"')
    if text[:1] in ("@", "?"):
        text = "\\" + text
    return text


def resource_name(key):
    return key.replace(".", "_")


def build(entries):
    """Returns {relative path: file text} for every language."""
    langs = []
    for langs_of_key in entries.values():
        for lang in langs_of_key:
            if lang not in langs:
                langs.append(lang)
    names = [resource_name(k) for k in entries]
    if len(set(names)) != len(names):
        fail("two keys become the same Android name (a.b and a_b?)")
    files = {}
    for lang in langs:
        qualifier = QUALIFIER.get(lang, lang)
        folder = f"values-{qualifier}" if qualifier else "values"
        lines = [
            '<?xml version="1.0" encoding="utf-8"?>',
            f"<!-- {MARK} from app/i18n/strings.txt. Do not edit. -->",
            "<resources>",
        ]
        for key, langs_of_key in entries.items():
            if lang in langs_of_key:
                english = placeholders(langs_of_key["en"])
                value = android_text(langs_of_key[lang], english)
                lines.append(f'    <string name="{resource_name(key)}">{value}</string>')
        lines.append("</resources>")
        files[f"{folder}/strings.xml"] = "\n".join(lines) + "\n"
    files["values/strings.xml"] = with_language_list(files["values/strings.xml"], langs, entries)
    return files


def locale_tag(lang):
    """The BCP-47 tag the app switches to: zh -> zh-Hans, pt-BR -> pt-BR."""
    qualifier = QUALIFIER.get(lang, lang)
    if qualifier.startswith("b+"):
        return qualifier[2:].replace("+", "-")
    return qualifier.replace("-r", "-") or lang


def with_language_list(xml, langs, entries):
    """Adds the language tags the app offers (those with a language.name line),
    English first, to the default resources."""
    offered = [lang for lang in langs if lang in entries.get(LANGUAGE_KEY, {})]
    offered.sort(key=lambda lang: lang != "en")
    items = [f"        <item>{locale_tag(lang)}</item>" for lang in offered]
    block = ["    <string-array name=\"supported_language_tags\">", *items, "    </string-array>"]
    return xml.replace("</resources>", "\n".join(block) + "\n</resources>")


def coverage(entries):
    langs = sorted({lang for d in entries.values() for lang in d})
    for lang in langs:
        if lang == "en":
            continue
        missing = [k for k, d in entries.items() if lang not in d]
        done = len(entries) - len(missing)
        print(f"{lang}: {done}/{len(entries)} translated", end="")
        print(f"  (missing: {', '.join(missing)})" if missing else "")


def main():
    check = "--check" in sys.argv[1:]
    entries = parse(SOURCE.read_text(encoding="utf-8"))
    files = build(entries)
    stale = []
    for rel, text in files.items():
        path = RES / rel
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            stale.append(rel)
    # Generated files for languages no longer in strings.txt.
    for path in RES.glob("values*/strings.xml"):
        rel = path.relative_to(RES).as_posix()
        if rel not in files and MARK in path.read_text(encoding="utf-8"):
            stale.append(rel)

    if check:
        if stale:
            print("Out of date (run python i18n/gen_strings.py):", ", ".join(stale))
            sys.exit(1)
        print("Translations up to date.")
    else:
        for rel, text in files.items():
            path = RES / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        for rel in stale:
            if rel not in files:
                path = RES / rel
                path.unlink()
                if not any(path.parent.iterdir()):
                    path.parent.rmdir()
        print(f"Wrote {len(files)} language file(s).")
    coverage(entries)


if __name__ == "__main__":
    main()
