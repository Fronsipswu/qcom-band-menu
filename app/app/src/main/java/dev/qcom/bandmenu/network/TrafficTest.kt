package dev.qcom.bandmenu.network

import android.content.Context
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.Job
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.currentCoroutineContext
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.isActive
import kotlinx.coroutines.launch
import java.net.HttpURLConnection
import java.net.URL
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.atomic.AtomicLong
import kotlin.random.Random

/**
 * Test script for the Network page: keeps a few HTTP streams going so the
 * carriers stay active (an idle phone drops its SCells). [Config.streams]
 * parallel streams (one TCP connection can't fill a fast link), each a loop
 * of requests with a cache-buster, until stopped or the duration is up. Download reads a GET URL and discards it; upload POSTs generated bytes
 * to a POST URL. Process-wide, so it keeps going while the page is not shown.
 */
class TrafficTest private constructor(context: Context) {
    data class Config(
        val getUrl: String = "",
        val postUrl: String = "",
        val upload: Boolean = false,
        /** 0 = until stopped. */
        val seconds: Int = 0,
        /** Parallel streams, 1 to [MAX_STREAMS]. */
        val streams: Int = 1
    ) {
        val url get() = (if (upload) postUrl else getUrl).trim()
    }

    data class Run(
        val running: Boolean = false,
        val upload: Boolean = false,
        val mbps: Double = 0.0,
        /** Seconds left, or null when there's no time limit. */
        val remaining: Int? = null,
        val error: String? = null
    )

    private val prefs = context.applicationContext.getSharedPreferences("traffic_test", Context.MODE_PRIVATE)
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)
    private val _config = MutableStateFlow(
        Config(
            getUrl = prefs.getString("get", DEFAULT_GET) ?: "",
            postUrl = prefs.getString("post", DEFAULT_POST) ?: "",
            upload = prefs.getBoolean("upload", false),
            seconds = prefs.getInt("seconds", 0),
            streams = prefs.getInt("streams", 1).coerceIn(1, MAX_STREAMS)
        )
    )
    val config: StateFlow<Config> = _config
    private val _run = MutableStateFlow(Run())
    val run: StateFlow<Run> = _run

    private var job: Job? = null
    private val open = ConcurrentHashMap.newKeySet<HttpURLConnection>()
    private val bytes = AtomicLong()
    @Volatile private var lastError: String? = null

    fun save(c: Config) {
        _config.value = c
        prefs.edit().putString("get", c.getUrl).putString("post", c.postUrl)
            .putBoolean("upload", c.upload).putInt("seconds", c.seconds)
            .putInt("streams", c.streams.coerceIn(1, MAX_STREAMS)).apply()
    }

    /** False if the current mode's URL isn't usable (the caller opens the setup). */
    fun start(): Boolean {
        val c = _config.value
        if (job?.isActive == true) return true
        if (!(c.url.startsWith("https://") || c.url.startsWith("http://"))) return false
        lastError = null
        bytes.set(0)
        val endAt = if (c.seconds > 0) System.nanoTime() + c.seconds * 1_000_000_000L else 0L
        job = scope.launch {
            val workers = List(c.streams.coerceIn(1, MAX_STREAMS)) { launch { stream(c, endAt) } }
            var last = bytes.get()
            var lastAt = System.nanoTime()
            while (isActive) {
                _run.value = Run(true, c.upload, _run.value.mbps, remaining(endAt), lastError)
                delay(1000)
                val now = System.nanoTime()
                val total = bytes.get()
                val mbps = (total - last) * 8.0 / ((now - lastAt) / 1e9) / 1e6
                last = total; lastAt = now
                if (endAt != 0L && now >= endAt) break
                _run.value = Run(true, c.upload, mbps, remaining(endAt), lastError)
            }
            workers.forEach { it.cancel() }
            closeAll()
            _run.value = Run(false, c.upload, error = lastError)
        }
        return true
    }

    fun stop() {
        job?.cancel()
        closeAll()
        _run.value = Run(false, _config.value.upload, error = lastError)
    }

    private fun remaining(endAt: Long) =
        if (endAt == 0L) null else ((endAt - System.nanoTime() + 999_999_999L) / 1_000_000_000L).toInt().coerceAtLeast(0)

    private fun closeAll() { open.forEach { runCatching { it.disconnect() } }; open.clear() }

    /** One stream: back-to-back requests, as the shell loop does. */
    private suspend fun stream(c: Config, endAt: Long) {
        val buf = ByteArray(64 * 1024).also { Random.nextBytes(it) }
        while (currentCoroutineContext().isActive && (endAt == 0L || System.nanoTime() < endAt)) {
            val sep = if ('?' in c.url) '&' else '?'
            val url = "${c.url}${sep}run=${System.nanoTime()}_${Random.nextInt(32768)}"
            var conn: HttpURLConnection? = null
            try {
                conn = URL(url).openConnection() as HttpURLConnection
                open.add(conn)
                conn.connectTimeout = 5000
                conn.readTimeout = 15000
                val until = System.nanoTime() + REQUEST_MAX_NS
                if (c.upload) {
                    conn.requestMethod = "POST"
                    conn.doOutput = true
                    conn.setFixedLengthStreamingMode(UPLOAD_BYTES)
                    conn.outputStream.use { out ->
                        var left = UPLOAD_BYTES
                        while (left > 0 && System.nanoTime() < until && currentCoroutineContext().isActive) {
                            val n = minOf(left, buf.size.toLong()).toInt()
                            out.write(buf, 0, n); bytes.addAndGet(n.toLong()); left -= n
                        }
                    }
                    conn.responseCode
                } else {
                    val code = conn.responseCode
                    if (code !in 200..299) throw java.io.IOException("HTTP $code")
                    conn.inputStream.use { ins ->
                        while (System.nanoTime() < until && currentCoroutineContext().isActive) {
                            val n = ins.read(buf)
                            if (n < 0) break
                            bytes.addAndGet(n.toLong())
                        }
                    }
                }
                lastError = null
            } catch (e: Exception) {
                if (!currentCoroutineContext().isActive) break
                lastError = e.message?.take(60) ?: e.javaClass.simpleName
                delay(1000)
            } finally {
                conn?.let { open.remove(it); runCatching { it.disconnect() } }
            }
        }
    }

    companion object {
        const val MAX_STREAMS = 8
        private const val REQUEST_MAX_NS = 60_000_000_000L
        private const val UPLOAD_BYTES = 25_000_000L
        private const val DEFAULT_GET = "https://speedtest-sp1.3bb.co.th.prod.hosts.ooklaserver.net:8080/download?size=25000000"
        private const val DEFAULT_POST = "https://speedtest-sp1.3bb.co.th.prod.hosts.ooklaserver.net:8080/upload"

        @Volatile private var instance: TrafficTest? = null
        fun get(context: Context): TrafficTest =
            instance ?: synchronized(this) { instance ?: TrafficTest(context).also { instance = it } }
    }
}
