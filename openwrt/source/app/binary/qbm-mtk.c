static void chains_add(struct mtk_carrier *s, int which, const double *v, const int *ok, int n) {
    for (int i = 0; i < n && i < 4; i++) if (ok[i]) mm_add(&s->chain[which][i], v[i]);
}

/* The carrier index of an NR cell the configuration lists (PCI, SSB NR-ARFCN); before any
 * configuration the first cell measured is taken as the PCell. */
static int mtk_nr_cc(int pci, uint32_t arfcn) {
    int any = 0;
    for (int i = 0; i < MTK_CC; i++) {
        if (!mtk_nr_cfg[i].known) continue;
        any = 1;
        if (mtk_nr_cfg[i].pci == pci && mtk_nr_cfg[i].arfcn == arfcn) return i;
    }
    if (any) return -1;
    mtk_nr_cfg[0].known = 1; mtk_nr_cfg[0].pci = pci; mtk_nr_cfg[0].arfcn = arfcn;
    return 0;
}

/* Active DL BWP: bandwidth (its RB count when that is a whole channel, else the quantized
 * index) and SCS. */
static void mtk_bwp(const struct mtk_node *cfg, struct mtk_nr_cfg *c) {
    /* (SCS index, RBs) of a whole channel -> MHz, TS 38.101-1 table 5.3.2-1 */
    static const struct { uint8_t scs; uint16_t rbs, mhz; } whole[] = {
        { 0, 25, 5 }, { 0, 52, 10 }, { 0, 79, 15 }, { 0, 106, 20 }, { 0, 133, 25 }, { 0, 160, 30 }, { 0, 188, 35 },
        { 0, 216, 40 }, { 0, 242, 45 }, { 0, 270, 50 },
        { 1, 11, 5 }, { 1, 24, 10 }, { 1, 38, 15 }, { 1, 51, 20 }, { 1, 65, 25 }, { 1, 78, 30 }, { 1, 92, 35 },
        { 1, 106, 40 }, { 1, 119, 45 }, { 1, 133, 50 }, { 1, 162, 60 }, { 1, 189, 70 }, { 1, 217, 80 }, { 1, 245, 90 },
        { 1, 273, 100 },
    };
    struct mtk_node b;
    if (!mtk_item(cfg, "Active DL BWP Config", &b)) return;
    int64_t bw, scs, rbs;
    int have_scs = mtk_get(&b, "Sub carrier Spacing", &scs), mhz = 0;
    if (have_scs && mtk_get(&b, "BWP size", &rbs))
        for (unsigned i = 0; i < sizeof whole / sizeof whole[0]; i++)
            if (whole[i].scs == scs && whole[i].rbs == rbs) mhz = whole[i].mhz;
    if (!mhz && mtk_get(&b, "Bandwidth", &bw) && bw >= 0 && bw < (int64_t)(sizeof MTK_NR_BW / sizeof MTK_NR_BW[0]))
        mhz = MTK_NR_BW[bw];
    c->bw = mhz;
    c->scs = have_scs && scs >= 0 && scs < 5 ? 15 << scs : 0;
}

static void mtk_nr_config(const struct mtk_node *f) {
    struct mtk_nr_cfg cells[MTK_CC];
    memset(cells, 0, sizeof cells);
    int64_t v;
    struct mtk_node x, items[16];
    cells[0].known = 1;
    if (mtk_get(f, "Physical Cell ID", &v)) cells[0].pci = (int)v;
    if (mtk_get(f, "DL NARFCN", &v)) cells[0].arfcn = (uint32_t)v;
    if (mtk_get(f, "DL Frequency Band", &v)) cells[0].band = (int)v;
    if (mtk_item(f, "PDSCH Config", &x) && mtk_get(&x, "Max Rank", &v)) cells[0].max_layers = (int)v + 1;
    mtk_bwp(f, &cells[0]);
    if (mtk_item(f, "PUSCH Config", &x) && mtk_get(&x, "Tx Config Type", &v)) cells[0].codebook = v == 0;
    int nsets = mtk_items(f, "SRS Resource Set Config", items, 16);
    for (int i = 0; i < nsets; i++) {
        struct mtk_node res[16];
        int nr = mtk_items(&items[i], "SRS Resources", res, 16);
        for (int k = 0; k < nr; k++)
            if (mtk_get(&res[k], "Number of SRS Ports", &v) && v > cells[0].srs_ports) cells[0].srs_ports = (int)v;
    }
    int ns = mtk_items(f, "Scell Config", items, 16);
    for (int i = 0; i < ns; i++) {
        if (!mtk_get(&items[i], "Cell Index", &v) || v <= 0 || v >= MTK_CC) continue;
        struct mtk_nr_cfg *c = &cells[v];
        c->known = 1;
        if (mtk_get(&items[i], "Physical Cell ID", &v)) c->pci = (int)v;
        if (mtk_get(&items[i], "DL NARFCN", &v)) c->arfcn = (uint32_t)v;
        if (mtk_get(&items[i], "DL Frequency Band", &v)) c->band = (int)v;
        if (mtk_item(&items[i], "PDSCH Config", &x) && mtk_get(&x, "Max Rank", &v)) c->max_layers = (int)v + 1;
        mtk_bwp(&items[i], c);
    }
    memcpy(mtk_nr_cfg, cells, sizeof cells);
}

static int mtk_cc_of(const struct mtk_node *f, const char *name) {
    int64_t v;
    return mtk_get(f, name, &v) && v >= 0 && v < MTK_CC ? (int)v : 0;
}

/* The NR PCell's identity, for RRC messages (which carry no cell). */
static void mtk_pcell(int *pci, uint32_t *arfcn) {
    *pci = mtk_nr_cfg[0].known ? mtk_nr_cfg[0].pci : -1;
    *arfcn = mtk_nr_cfg[0].arfcn;
}

static void mtk_nr_log(uint16_t code, const struct mtk_node *f, long now) {
    int64_t v;
    int ok;
    struct mtk_node items[64];
    if (code == 0x9014) {
        mtk_nr_config(f);
    } else if (code == 0x9101) {
        /* NRRC measurement: the SS-RSRQ the UE reports to the network, as a
         * 0.5 dB index (0 = below -43 dB); the NSG reference converts it as
         * -43 + 0.5*index. This is the cell-level value; the L1 log (0x9001)
         * stays the fallback. */
        int64_t pci = -1, arfcn = -1, rsrq = -1, si = -1;
        mtk_get(f, "Physical Cell ID", &pci);
        mtk_get(f, "Serv NRarfcn", &arfcn);
        if (!mtk_get(f, "Serv Rsrq", &rsrq) || rsrq < 0 || rsrq > 127) return;
        int cc = -1;
        for (int i = 0; i < MTK_CC; i++)
            if (mtk_nr_cfg[i].known && mtk_nr_cfg[i].pci == (int)pci
                && mtk_nr_cfg[i].arfcn == (uint32_t)arfcn) { cc = i; break; }
        if (cc < 0 && mtk_get(f, "ServIndex", &si) && si >= 0 && si < MTK_CC) cc = (int)si;
        if (cc < 0) cc = 0;
        mh_put(&mtk_nr[cc].rrc_rsrq, -43.0 + 0.5 * (double)rsrq, now);
    } else if (code == 0x9001) {
        int64_t pci, arfcn;
        if (!mtk_get(f, "PCI", &pci) || !mtk_get(f, "NARFCN", &arfcn)) return;
        int cc = mtk_nr_cc((int)pci, (uint32_t)arfcn);
        if (cc < 0) return;
        if (!mtk_nr_cfg[cc].band && mtk_get(f, "Band", &v)) mtk_nr_cfg[cc].band = (int)v;
        struct mtk_carrier *s = &mtk_nr[cc];
        int n = mtk_items(f, "Serving Cell SSS Measurement Records", items, 64);
        /* the strongest beam per measurement occasion (SFN, subframe); serving-beam records,
         * or the strongest beams when none is flagged (SCell records never are) */
        int best[64], nbest = 0, nserving = 0;
        for (int i = 0; i < n; i++) {
            int64_t sfn = -1, sf = -1, rsrp = -999;
            mtk_get(&items[i], "SFN", &sfn); mtk_get(&items[i], "Subframe", &sf); mtk_get(&items[i], "RSRP", &rsrp);
            int j;
            for (j = 0; j < nbest; j++) {
                int64_t bs = -1, bf = -1, br = -999;
                mtk_get(&items[best[j]], "SFN", &bs); mtk_get(&items[best[j]], "Subframe", &bf); mtk_get(&items[best[j]], "RSRP", &br);
                if (bs == sfn && bf == sf) { if (rsrp > br) best[j] = i; break; }
            }
            if (j == nbest) best[nbest++] = i;
            if (mtk_get(&items[i], "Serving Beam Flag", &v) && v) nserving++;
        }
        for (int i = 0; i < n; i++) {
            int use = 0;
            if (nserving) use = mtk_get(&items[i], "Serving Beam Flag", &v) && v;
            else for (int j = 0; j < nbest; j++) if (best[j] == i) use = 1;
            if (!use) continue;
            double d;
            if ((d = mtk_getd(&items[i], "RSRP", &ok)), ok) mm_add(&s->q[MQ_RSRP], d);
            if ((d = mtk_getd(&items[i], "RSRQ", &ok)), ok) mm_add(&s->q[MQ_RSRQ], d);
            if ((d = mtk_getd(&items[i], "SINR", &ok)), ok) mm_add(&s->q[MQ_SINR], d);
            static const char *const rsrp_rx[] = { "RSRP RX0", "RSRP RX1" }, *const rsrq_rx[] = { "RSRQ RX0", "RSRQ RX1" },
                                     *const sinr_rx[] = { "SINR RX0", "SINR RX1" };
            double cv[2]; int cok[2];
            for (int c = 0; c < 2; c++) cv[c] = mtk_getd(&items[i], rsrp_rx[c], &cok[c]);
            chains_add(s, MC_RSRP, cv, cok, 2);
            for (int c = 0; c < 2; c++) cv[c] = mtk_getd(&items[i], rsrq_rx[c], &cok[c]);
            chains_add(s, MC_RSRQ, cv, cok, 2);
            for (int c = 0; c < 2; c++) cv[c] = mtk_getd(&items[i], sinr_rx[c], &cok[c]);
            chains_add(s, MC_SINR, cv, cok, 2);
            s->any = 1;
        }
        for (int j = 0; j < nbest; j++) {
            double d = mtk_getd(&items[best[j]], "SINR", &ok);
            if (ok) mm_add(&s->q[MQ_BSINR], d);
        }
    } else if (code == 0x9023) {
        struct mtk_carrier *s = &mtk_nr[mtk_cc_of(f, "Carrier index")];
        int n = mtk_items(f, "Sync TRS Measurement records", items, 64);
        for (int i = 0; i < n; i++) {
            double d = mtk_getd(&items[i], "Sync TRS SNR avarage", &ok);
            if (!ok) d = mtk_getd(&items[i], "Sync TRS SNR average", &ok);
            if (ok) mm_add(&s->q[MQ_CSINR], d);
            static const char *const rx[] = { "Sync TRS SNR RX0", "Sync TRS SNR RX1", "Sync TRS SNR RX2", "Sync TRS SNR RX3" };
            double cv[4]; int cok[4];
            /* -40: an RX path this carrier does not use (n28 SCell: RX2/RX3) */
            for (int c = 0; c < 4; c++) { cv[c] = mtk_getd(&items[i], rx[c], &cok[c]); if (cok[c] && cv[c] == -40) cok[c] = 0; }
            chains_add(s, MC_CSINR, cv, cok, 4);
            /* the same TRS is measured on CSI-RS: its per-path RSRP is the CRSRP
             * fallback when the modem sends no dedicated CSIRS measurement */
            static const char *const rsrp_rx[] = { "Sync TRS RSRP RX0", "Sync TRS RSRP RX1", "Sync TRS RSRP RX2", "Sync TRS RSRP RX3" };
            for (int c = 0; c < 4; c++) {
                cv[c] = mtk_getd(&items[i], rsrp_rx[c], &cok[c]);
                if (cok[c] && (cv[c] < -162 || cv[c] > 22)) cok[c] = 0;
            }
            chains_add(s, MC_TRSRP, cv, cok, 4);
            s->any = 1;
        }
    } else if (code == 0x9015) {
        int n = mtk_items(f, "Csi Records", items, 64);
        for (int i = 0; i < n; i++) {
            struct mtk_carrier *s = &mtk_nr[mtk_cc_of(&items[i], "Carrier Index")];
            if (mtk_get(&items[i], "WB CQI0 Valid", &v) && v && mtk_get(&items[i], "WB CQI0 Value", &v)) mh_put(&s->last[ML_CQI], (double)v, now);
            /* the RI field is a 0-based rank index */
            if (mtk_get(&items[i], "RI Valid", &v) && v && mtk_get(&items[i], "RI Value", &v)) mh_put(&s->last[ML_RI], (double)v + 1, now);
        }
    } else if (code == 0x9016) {
        /* CSI-RS RSRP per RX path (the antenna card's CRSRP). V2 carries the carrier
         * index; V1 only the PCI, matched against the configured cells. */
        int cc = 0;
        if (mtk_get(f, "Carrier Index", &v) && v >= 0 && v < MTK_CC) {
            cc = (int)v;
        } else {
            int64_t pci = -1;
            mtk_get(f, "PCI", &pci);
            for (int i = 0; i < MTK_CC; i++)
                if (mtk_nr_cfg[i].known && mtk_nr_cfg[i].pci == (int)pci) { cc = i; break; }
        }
        struct mtk_carrier *s = &mtk_nr[cc];
        static const char *const rsrp_rx[] = { "RSRP RX0", "RSRP RX1", "RSRP RX2", "RSRP RX3" };
        int n = mtk_items(f, "Serving Cell CSIRS Measurement Records", items, 64);
        for (int i = 0; i < n; i++) {
            double cv[4]; int cok[4];
            for (int c = 0; c < 4; c++) {
                cv[c] = mtk_getd(&items[i], rsrp_rx[c], &cok[c]);
                /* the EDB's range: an RX path the carrier does not use stays out */
                if (cok[c] && (cv[c] < -162 || cv[c] > 22)) cok[c] = 0;
            }
            chains_add(s, MC_CRSRP, cv, cok, 4);
            s->any = 1;
        }
    } else if (code == 0x9007) {
        struct mtk_carrier *s = &mtk_nr[mtk_cc_of(f, "Carrier Index")];
        int64_t k0 = 0, k1 = 0, n = 0, t0 = 0, t1 = 0, bler;
        mtk_get(f, "MIMO PDSCH Throughput0", &k0); mtk_get(f, "MIMO PDSCH Throughput1", &k1);
        mtk_get(f, "Total DL Assign Num", &n);
        mtk_get(f, "DL TB0 Size", &t0); mtk_get(f, "DL TB1 Size", &t1);
        mh_put(&s->last[ML_MBPS], (double)(k0 + k1) * 0.008, now);
        /* qbm-diagd's mbps_sched counts every scheduled TB: average TB size x assignments */
        mh_put(&s->last[ML_MBPS_SCHED], (double)(t0 + t1) * (double)n * 8 / 1e6, now);
        mh_put(&s->last[ML_TB], (double)n, now);
        if (mtk_get(f, "DL BLER", &bler)) mh_put(&s->last[ML_BLER], (double)bler, now);
        else s->last[ML_BLER].at = 0;
    } else if (code == 0x9003) {
        struct mtk_carrier *s = &mtk_nr[mtk_cc_of(f, "Carrier Index")];
        int64_t kbs = 0, bler;
        mtk_get(f, "UL throughput", &kbs);
        mh_put(&s->last[ML_UL_MBPS], (double)kbs * 0.008, now);
        if (mtk_get(f, "UL BLER", &bler)) mh_put(&s->last[ML_UL_BLER], (double)bler, now);
    } else if (code == 0x9009) {
        struct mtk_carrier *s = &mtk_nr[mtk_cc_of(f, "Carrier Index")];
        int n = mtk_items(f, "DCI Info", items, 64);
        for (int i = 0; i < n; i++) {
            struct mtk_node dl, ul;
            if (mtk_item(&items[i], "DL DCI Info", &dl) && mtk_get(&dl, "DL DCI valid", &v) && v) {
                double d;
                if ((d = mtk_getd(&dl, "MCS index 1", &ok)), ok) mm_add(&s->d[MD_MCS], d);
                if ((d = mtk_getd(&dl, "NUM RB", &ok)), ok) mm_add(&s->d[MD_RBS], d);
                if (mtk_get(&dl, "Num of layers", &v)) mm_add(&s->d[MD_LAYERS], (double)v + 1);
                if (mtk_get(&dl, "MCS type 1", &v) && v >= 0 && v < 4) s->mod[v]++;
            }
            if (mtk_item(&items[i], "UL DCI Info", &ul) && mtk_get(&ul, "UL Grant Valid", &v) && v) {
                double d;
                if ((d = mtk_getd(&ul, "MCS index", &ok)), ok) mm_add(&s->d[MD_UL_MCS], d);
                if ((d = mtk_getd(&ul, "NUM RB", &ok)), ok) mm_add(&s->d[MD_UL_RBS], d);
                if (mtk_get(&ul, "Number of layers", &v)) mm_add(&s->d[MD_UL_LAYERS], (double)v + 1);
                if (mtk_get(&ul, "Modulation type", &v) && v >= 0 && v < 5) s->ul_mod[v]++;
            }
        }
    } else if (code == 0x9011 || code == 0x900E) {
        struct mtk_carrier *s = &mtk_nr[mtk_cc_of(f, "Carrier Index")];
        int n = mtk_items(f, code == 0x9011 ? "Pusch Power Control Records" : "Pucch Power Control Records", items, 64);
        for (int i = 0; i < n; i++) {
            double d = mtk_getd(&items[i], "Transmitted Power", &ok);
            if (!ok) d = mtk_getd(&items[i], "Power", &ok);
            if (ok) mm_add(&s->q[code == 0x9011 ? MQ_UL_PWR : MQ_UL_PUCCH], d);
        }
    } else if (code == 0x9083) {
        /* MAC DL TBs: every DL-SCH TB for the C-RNTI. No carrier index: the total goes on
         * the PCell (TB counting, as qbm-diagd does on Qualcomm; "mbps_tb"). */
        struct mtk_carrier *s = &mtk_nr[0];
        int n = mtk_items(f, "DL TB Records", items, 64);
        for (int i = 0; i < n; i++) {
            int64_t type, ch, tb = 0;
            if (mtk_get(&items[i], "RNTI Type", &type) && type == 0 && mtk_get(&items[i], "Transport Channel", &ch) && ch == 2) {
                mtk_get(&items[i], "TB", &tb);
                s->dl_tb_bytes += (long)tb;
                s->dl_tbs++;
            }
        }
    } else if (code == 0x9084) {
        /* MAC UL TBs: one per new MAC PDU, grant size with padding. No carrier index. */
        struct mtk_carrier *s = &mtk_nr[0];
        int n = mtk_items(f, "UL TB Records", items, 64);
        for (int i = 0; i < n; i++) {
            int64_t type, grant = 0;
            if (mtk_get(&items[i], "RNTI Type", &type) && type == 0) {
                mtk_get(&items[i], "UL Grant", &grant);
                s->ul_tb_bytes += (long)grant;
                s->ul_tbs++;
            }
        }
    } else if (code == 0x9006) {
        struct mtk_node m;
        /* the RAR's timing advance (MSG2), raw index */
        if (mtk_item(f, "MSG2 Info", &m) && mtk_get(&m, "Timing Advance Value", &v)) mtk_ta_nr = (int)v;
        else if (mtk_get(f, "Timing Advance Value", &v)) mtk_ta_nr = (int)v;
    } else if (code == 0x9002) {
        int64_t arfcn;
        if (!mtk_get(f, "NARFCN", &arfcn)) return;
        int n = mtk_items(f, "Neighbor SSB Cell Measurement Records", items, 64);
        for (int i = 0; i < n; i++) {
            struct mtk_node cells[32];
            int nc = mtk_items(&items[i], "Neighbor Cells", cells, 32);
            for (int k = 0; k < nc; k++) {
                int64_t pci, ssb = -1, rsrp = 0, rsrq = 0;
                if (!mtk_get(&cells[k], "PCI", &pci)) continue;
                mtk_get(&cells[k], "SSB Index", &ssb); mtk_get(&cells[k], "RSRP", &rsrp); mtk_get(&cells[k], "RSRQ", &rsrq);
                int slot = -1, oldest = 0;
                for (int j = 0; j < MTK_NB_MAX; j++) {
                    if (mtk_nb[j].known && mtk_nb[j].arfcn == (uint32_t)arfcn && mtk_nb[j].pci == pci) { slot = j; break; }
                    if (!mtk_nb[j].known) { if (slot < 0) slot = j; }
                    else if (mtk_nb[j].at < mtk_nb[oldest].at) oldest = j;
                }
                if (slot < 0) slot = oldest;
                mtk_nb[slot].known = 1; mtk_nb[slot].arfcn = (uint32_t)arfcn; mtk_nb[slot].pci = (int)pci;
                mtk_nb[slot].ssb = (int)ssb; mtk_nb[slot].rsrp = (double)rsrp; mtk_nb[slot].rsrq = (double)rsrq; mtk_nb[slot].at = now;
            }
        }
    }
}

/* The serving-cell selector is spelled differently per log: "Carrier Index"
 * (physical config, PUSCH/PUCCH), "Serving Cell Index" (throughput) and
 * "Carrier type"/"Carrier Type" (serving/neighbour measurement). Its value is
 * the MAC serving-cell index, which is NOT the RRC SCell order of 0x7105 (the
 * EDB notes "not scell index configured by RRC"): mtk_lte_idx maps it to the
 * configured slot, learned from each cell's EARFCN/PCI. */
static int mtk_lte_idx[MTK_CC];
static void mtk_lte_slots_reset(void) { for (int i = 0; i < MTK_CC; i++) mtk_lte_idx[i] = i; }

/* A slot the modem stops naming (an SCell released without a CA event this
 * daemon saw) keeps its configuration in the table. Forget it once no record
 * has named it for MTK_LTE_STALE_MS, so the stats stop listing it. */
static void mtk_lte_expire(long now) {
    for (int i = 0; i < MTK_CC; i++) {
        struct mtk_lte_cfg *c = &mtk_lte_cfg[i];
        if (c->known && now - c->seen > MTK_LTE_STALE_MS) { c->known = 0; c->band = 0; }
    }
}

static int mtk_lte_sel(const struct mtk_node *f, int *raw) {
    int64_t v;
    *raw = 0;
    if (mtk_get(f, "Carrier Index", &v) || mtk_get(f, "Serving Cell Index", &v)
        || mtk_get(f, "Carrier type", &v) || mtk_get(f, "Carrier Type", &v))
        *raw = v >= 0 && v < MTK_CC ? (int)v : 0;
    return mtk_lte_idx[*raw];
}

/* LTE (EL1/ERRC logs): mapped from the database names. */
static void mtk_lte_log(uint16_t code, const struct mtk_node *f, long now) {
    int64_t v;
    int ok;
    struct mtk_node items[64];
    int raw;
    int slot = mtk_lte_sel(f, &raw);
    if (code == 0x7102) {
        /* ERRC OTA: feed DL-DCCH/DL-CCCH to the LTE RRC decoder; an SCell
         * addition carries its antennaPortsCount there. */
        int64_t pdu = 0;
        if (!mtk_get(f, "PDU Num", &pdu)) return;
        int channel = pdu == 3 ? 0 : pdu == 2 ? 1 : -1;   /* dlDcch / dlCcch */
        if (channel < 0) return;
        static int64_t bytes[16384];
        static unsigned char pdu_buf[16384];
        int n = mtk_list(f, "RRC Payload", bytes, (int)(sizeof bytes / sizeof bytes[0]));
        if (n <= 0) return;
        for (int i = 0; i < n; i++) pdu_buf[i] = (unsigned char)bytes[i];
        lte_decode(&mtk_lte_rrc, &mtk_lte_rrc_cb, channel, pdu_buf, (size_t)n);
    } else if (code == 0x7104) {
        /* ERRC_SIB_Read_Info: the MIB's TX antenna count with the cell identity */
        int64_t res = 1, pci = -1, earfcn = -1, ants = 0;
        struct mtk_node mib;
        if (!mtk_get(f, "MIBSIB Read Result", &res) || res != 0) return;
        if (!mtk_get(f, "Physical Cell ID", &pci) || pci < 0) return;
        if (!mtk_get(f, "Freq", &earfcn) || earfcn <= 0) return;
        if (!mtk_item(f, "MIB Content", &mib)) return;
        if (!mtk_get(&mib, "Antennas", &ants) || ants < 1 || ants > 8) return;
        mtk_lte_tx_put((uint32_t)earfcn, (int)pci, (int)ants, now);
    } else if (code == 0x700C) {
        /* EL1_PBCH_DecodingResults: the same MIB field; the record has the
         * EARFCN but no PCI, so take the PCI from the configured cell. */
        int n = mtk_items(f, "Pbch Decoding Records", items, 64);
        for (int i = 0; i < n; i++) {
            int64_t crc = 0, cfg = -1, earfcn = -1;
            if (!mtk_get(&items[i], "CRC Result", &crc) || !crc) continue;
            if (!mtk_get(&items[i], "Transmit Antenna Config", &cfg)) continue;
            if (!mtk_get(&items[i], "EARFCN", &earfcn) || earfcn <= 0) continue;
            int tx = cfg == 0 ? 1 : cfg == 1 ? 2 : cfg == 2 ? 4 : 0;
            if (!tx) continue;
            int pci = -1;
            for (int k = 0; k < MTK_CC; k++)
                if (mtk_lte_cfg[k].known && mtk_lte_cfg[k].earfcn == (uint32_t)earfcn) { pci = mtk_lte_cfg[k].pci; break; }
            if (pci >= 0) mtk_lte_tx_put((uint32_t)earfcn, pci, tx, now);
        }
    } else if (code == 0x7105) {
        /* a CA configuration event: re-read the cells and re-learn the indices */
        mtk_lte_slots_reset();
        for (int i = 1; i < MTK_CC; i++) mtk_lte_cfg[i].known = 0;
        struct mtk_node pcc;
        if (mtk_item(f, "PCC Config", &pcc)) {
            struct mtk_lte_cfg *c = &mtk_lte_cfg[0];
            c->known = 1; c->state = 2; c->seen = now; c->band = 0;
            if (mtk_get(&pcc, "Earfcn", &v)) c->earfcn = (uint32_t)v;
            if (mtk_get(&pcc, "Physical Cell ID", &v)) c->pci = (int)v;
            if (mtk_get(&pcc, "Freq Band Indicator", &v)) c->band = (int)v;
            if (mtk_get(&pcc, "DL Bandwidth", &v) && v >= 0 && v < 6) c->bw = MTK_LTE_BW[v];
        }
        int64_t nsc = 0;
        mtk_get(f, "Num of SCells", &nsc);
        int n = mtk_items(f, "SCC Config", items, MTK_CC - 1);
        for (int i = 0; i < n && i < nsc; i++) {
            struct mtk_lte_cfg *c = &mtk_lte_cfg[i + 1];
            c->known = 1; c->seen = now; c->band = 0;
            if (mtk_get(&items[i], "Earfcn", &v)) c->earfcn = (uint32_t)v;
            if (mtk_get(&items[i], "Physical Cell ID", &v)) c->pci = (int)v;
            if (mtk_get(&items[i], "Freq Band Indicator", &v)) c->band = (int)v;
            if (mtk_get(&items[i], "DL Bandwidth", &v) && v >= 0 && v < 6) c->bw = MTK_LTE_BW[v];
            c->state = 1 + (mtk_get(&items[i], "DL State", &v) && v);
        }
    } else if (code == 0x7018) {
        /* The physical configuration carries the EARFCN but no PCI; match the
         * configured cell by EARFCN so the MAC index does not decide identity. */
        int64_t earfcn = 0;
        int found = -1;
        if (mtk_get(f, "EARFCN", &earfcn))
            for (int i = 0; i < MTK_CC; i++)
                if (mtk_lte_cfg[i].known && mtk_lte_cfg[i].earfcn == (uint32_t)earfcn) { found = i; break; }
        if (found >= 0) { slot = found; mtk_lte_idx[raw] = found; }
        struct mtk_lte_cfg *c = &mtk_lte_cfg[slot];
        struct mtk_node ant;
        c->known = 1; c->seen = now;
        /* a new EARFCN means the old band no longer applies: the stats then
         * derive the band from the EARFCN */
        if (earfcn > 0) { if ((uint32_t)earfcn != c->earfcn) c->band = 0; c->earfcn = (uint32_t)earfcn; }
        if (mtk_item(f, "Antenna Config", &ant) && mtk_get(&ant, "Transmission Mode", &v)) c->tm = (int)v;
        if (mtk_get(f, "Downlink Bandwidth", &v) && v >= 0 && v < 6) c->bw = MTK_LTE_BW[v];
    } else if (code == 0x7001) {
        /* The record's PCI/EARFCN identify the cell: match the configured one,
         * then remember which slot this MAC index belongs to. */
        int64_t pci = -1, arfcn = -1;
        int found = -1, by_arfcn = -1;
        mtk_get(f, "PCI", &pci);
        mtk_get(f, "EARFCN", &arfcn);
        for (int i = 0; i < MTK_CC; i++) {
            if (!mtk_lte_cfg[i].known || mtk_lte_cfg[i].earfcn != (uint32_t)arfcn) continue;
            if (mtk_lte_cfg[i].pci == (int)pci) { found = i; break; }
            if (by_arfcn < 0) by_arfcn = i;
        }
        if (found < 0) found = by_arfcn;
        if (found >= 0) { slot = found; mtk_lte_idx[raw] = found; }
        struct mtk_carrier *s = &mtk_lte[slot];
        struct mtk_lte_cfg *c = &mtk_lte_cfg[slot];
        c->known = 1; c->seen = now;
        if (pci >= 0) c->pci = (int)pci;
        if (arfcn > 0) { if ((uint32_t)arfcn != c->earfcn) c->band = 0; c->earfcn = (uint32_t)arfcn; }
        int n = mtk_items(f, "Serving Cell Measurement Records", items, 64);
        for (int i = 0; i < n; i++) {
            double d, cv[2]; int cok[2];
            /* The EDB's valid ranges: a path the carrier does not use can still
             * carry a value, and must not count as an antenna. */
            if ((d = mtk_getd(&items[i], "RSRP", &ok)), ok && d >= -150 && d <= -30) mm_add(&s->q[MQ_RSRP], d);
            if ((d = mtk_getd(&items[i], "RSRQ", &ok)), ok && d >= -40 && d <= 10) mm_add(&s->q[MQ_RSRQ], d);
            if ((d = mtk_getd(&items[i], "SINR", &ok)), ok && d >= -20 && d <= 40) mm_add(&s->q[MQ_SINR], d);
            cv[0] = mtk_getd(&items[i], "RSRP RX0", &cok[0]); cv[1] = mtk_getd(&items[i], "RSRP RX1", &cok[1]);
            for (int k = 0; k < 2; k++) if (cok[k] && (cv[k] < -150 || cv[k] > -30)) cok[k] = 0;
            chains_add(s, MC_RSRP, cv, cok, 2);
            cv[0] = mtk_getd(&items[i], "RSRQ RX0", &cok[0]); cv[1] = mtk_getd(&items[i], "RSRQ RX1", &cok[1]);
            for (int k = 0; k < 2; k++) if (cok[k] && (cv[k] < -40 || cv[k] > 10)) cok[k] = 0;
            chains_add(s, MC_RSRQ, cv, cok, 2);
            cv[0] = mtk_getd(&items[i], "SINR RX0", &cok[0]); if (!cok[0]) cv[0] = mtk_getd(&items[i], "SINR Rx0", &cok[0]);
            cv[1] = mtk_getd(&items[i], "SINR RX1", &cok[1]); if (!cok[1]) cv[1] = mtk_getd(&items[i], "SINR Rx1", &cok[1]);
            for (int k = 0; k < 2; k++) if (cok[k] && (cv[k] < -20 || cv[k] > 40)) cok[k] = 0;
            chains_add(s, MC_SINR, cv, cok, 2);
            s->any = 1;
        }
    } else if (code == 0x700A) {
        /* UL grants: MCS, RBs and modulation per codeword (Serving Cell Index
         * is per record here, not on the log's root). */
        int n = mtk_items(f, "DCI Info", items, 64);
        for (int i = 0; i < n; i++) {
            struct mtk_carrier *s = &mtk_lte[mtk_cc_of(&items[i], "Serving Cell Index")];
            for (int g = 0; g < 2; g++) {
                struct mtk_node ul;
                if (!mtk_item(&items[i], g ? "UL DCI Grant1 Info" : "UL DCI Grant0 Info", &ul)) continue;
                if (!mtk_get(&ul, "UL Grant Valid", &v) || !v) continue;
                double d;
                if ((d = mtk_getd(&ul, "MCS IDX", &ok)), ok) mm_add(&s->d[MD_UL_MCS], d);
                if ((d = mtk_getd(&ul, "NUM RB", &ok)), ok) mm_add(&s->d[MD_UL_RBS], d);
                /* LTE UL modulation is QPSK(0)..256QAM(3); MTK_UL_MOD starts at BPSK */
                if (mtk_get(&ul, "Modulation type", &v) && v >= 0 && v < 4) s->ul_mod[v + 1]++;
                s->any = 1;
            }
        }
    } else if (code == 0x700D) {
        /* DL scheduling: PRBs and layers per TB, MCS and modulation per stream. */
        int n = mtk_items(f, "Pdsch Decoding Records", items, 64);
        for (int i = 0; i < n; i++) {
            int64_t rnti;
            if (!mtk_get(&items[i], "RNTI Type", &rnti) || rnti > 1) continue;   /* C-RNTI / SPS-C-RNTI */
            struct mtk_carrier *s = &mtk_lte[mtk_cc_of(&items[i], "Carrier Index")];
            double d;
            if ((d = mtk_getd(&items[i], "Number of RBs", &ok)), ok) mm_add(&s->d[MD_RBS], d);
            if (mtk_get(&items[i], "DL Layer", &v) && v > 0) mm_add(&s->d[MD_LAYERS], (double)v);
            else if (mtk_get(&items[i], "Number of Streams", &v) && v > 0) mm_add(&s->d[MD_LAYERS], (double)v);
            struct mtk_node st[4];
            int ns = mtk_items(&items[i], "Decoding Streams", st, 4);
            for (int k = 0; k < ns; k++) {
                int64_t tb = 0, crc = 1;
                /* TB-based PHY throughput, as qbm-diagd does on Qualcomm:
                 * every TB slot counts, bytes_all always, bytes_pass on CRC pass. */
                if (mtk_get(&st[k], "TB Size", &tb) && tb > 0) {
                    mtk_get(&st[k], "CRC Result", &crc);
                    s->dl_tb_bytes_all += (long)tb;
                    s->dl_tbs++;
                    if (crc) s->dl_tb_bytes += (long)tb;
                    else s->dl_tb_fail++;
                }
                if ((d = mtk_getd(&st[k], "MCS", &ok)), ok) mm_add(&s->d[MD_MCS], d);
                /* V2+ carry the modulation; V1's MCS uses the 36.213 table */
                if (mtk_get(&st[k], "Modulation Scheme", &v) && v >= 0 && v < 4) s->mod[v]++;
                else if (mtk_get(&st[k], "MCS", &v) && v >= 0)
                    s->mod[v <= 9 ? 0 : v <= 16 ? 1 : v <= 28 ? 2 : 3]++;
            }
            s->any = 1;
        }
    } else if (code == 0x7007 || code == 0x7008) {
        struct mtk_carrier *s = &mtk_lte[slot];
        int tb1 = code == 0x7008;
        int64_t bps = 0, bler, n;
        /* the EDB's unit is bits/sec (the NR throughput logs are KB/sec) */
        mtk_get(f, tb1 ? "MIMO PDSCH Throughput1" : "MIMO PDSCH Throughput0", &bps);
        mh_put(&s->last[tb1 ? ML_MBPS1 : ML_MBPS0], (double)bps / 1e6, now);
        if (mtk_get(f, tb1 ? "DL BLER1" : "DL BLER0", &bler)) mh_put(&s->last[tb1 ? ML_BLER1 : ML_BLER0], (double)bler, now);
        if (mtk_get(f, tb1 ? "DL TB Number1" : "DL TB Number0", &n)) mh_put(&s->last[tb1 ? ML_TB1 : ML_TB0], (double)n, now);
    } else if (code == 0x7003) {
        struct mtk_carrier *s = &mtk_lte[slot];
        int64_t bps = 0, bler;
        mtk_get(f, "UL throughput", &bps);
        mh_put(&s->last[ML_UL_MBPS], (double)bps / 1e6, now);
        if (mtk_get(f, "UL BLER", &bler)) mh_put(&s->last[ML_UL_BLER], (double)bler, now);
    } else if (code == 0x7014) {
        struct mtk_carrier *s = &mtk_lte[slot];
        int n = mtk_items(f, "Pusch Tx Reports", items, 64);
        for (int i = 0; i < n; i++) {
            double d = mtk_getd(&items[i], "Number of RBs", &ok);
            if (ok) mm_add(&s->d[MD_UL_RBS], d);
            /* the transmitted TB size (bytes) counts for UL throughput */
            int64_t tb = 0;
            if (mtk_get(&items[i], "TB Size", &tb) && tb > 0) { s->ul_tb_bytes += (long)tb; s->ul_tbs++; }
            if (mtk_get(&items[i], "Modulation Order", &v) && v >= 0 && v < 4) s->ul_mod[v + 1]++;
        }
    } else if (code == 0x7015 || code == 0x7012) {
        struct mtk_carrier *s = &mtk_lte[slot];
        int n = mtk_items(f, code == 0x7015 ? "Pusch Power Control Records" : "Pucch Power Control Records", items, 64);
        for (int i = 0; i < n; i++) {
            double d = mtk_getd(&items[i], "Power", &ok);
            if (ok) mm_add(&s->q[code == 0x7015 ? MQ_UL_PWR : MQ_UL_PUCCH], d);
        }
    } else if (code == 0x7006) {
        struct mtk_node m;
        if (mtk_item(f, "MSG2 Info", &m) && mtk_get(&m, "Timing Advance Value", &v)) mtk_ta_lte = (int)v;
        else if (mtk_get(f, "Timing Advance Value", &v)) mtk_ta_lte = (int)v;
    } else if (code == 0x7013) {
        int n = mtk_items(f, "Csf Records", items, 64);
        for (int i = 0; i < n; i++) {
            struct mtk_carrier *s = &mtk_lte[mtk_cc_of(&items[i], "Carrier Index")];
            int64_t rt;
            /* Reporting Type 0/1/3 carry CQI, 2/4 carry RI; a rank report's CQI
             * field is stale and must not be taken as a measurement. */
            if (!mtk_get(&items[i], "Reporting Type", &rt)) continue;
            if ((rt == 0 || rt == 1 || rt == 3) && mtk_get(&items[i], "CQI Codeword 0", &v))
                mh_put(&s->last[ML_CQI], (double)v, now);
            if ((rt == 2 || rt == 4) && mtk_get(&items[i], "Rank Indicator", &v))
                mh_put(&s->last[ML_RANK], (double)v + 1, now);
        }
    }
}

/* NRRC_PDU_Event: release, version, sub-version, PDU type (2 DL-CCCH, 3 DL-DCCH, ...),
 * u16 length, PDU. RRC setups and reconfigurations go to rrc_csi.c for CSI-RS ports. */
static void mtk_rrc_event(const struct mtk_node *f) {
    int64_t type;
    static int64_t pdu[MTK_PDU_MAX];
    static uint8_t bytes[MTK_PDU_MAX];
    if (!mtk_get(f, "RRC PDU type", &type)) return;
    int channel = type == 2 ? RRC_CSI_DL_CCCH : type == 3 ? RRC_CSI_DL_DCCH : 0;
    int n = mtk_list(f, "RRC PDU", pdu, MTK_PDU_MAX);
    if (n <= 0) return;
    for (int i = 0; i < n; i++) bytes[i] = (uint8_t)pdu[i];
    if (getenv("QBM_MTK_RRC_HEX")) {          /* debugging: every NR RRC PDU on stderr */
        fprintf(stderr, "rrc %d ", (int)type);
        for (int i = 0; i < n; i++) fprintf(stderr, "%02x", bytes[i]);
        fputc('\n', stderr);
    }
    if (!channel) return;
    int pci;
    uint32_t arfcn;
    mtk_pcell(&pci, &arfcn);
    rrc_csi_select(0);
    rrc_csi_pdu(channel, pci, arfcn, bytes, n);
}

static long mtk_codes_seen[2];   /* records, events decoded */

/* The last payload of each decoded code, for {"cmd":"mtk_log","code":"0x9001"}. */
static struct { uint16_t code; size_t len, cap; uint8_t *p; } mtk_last_rec[32];

static void mtk_keep(uint16_t code, const uint8_t *p, size_t n) {
    for (size_t i = 0; i < sizeof mtk_last_rec / sizeof mtk_last_rec[0]; i++) {
        if (mtk_last_rec[i].code && mtk_last_rec[i].code != code) continue;
        if (mtk_last_rec[i].cap < n) {
            uint8_t *q = realloc(mtk_last_rec[i].p, n);
            if (!q) return;
            mtk_last_rec[i].p = q;
            mtk_last_rec[i].cap = n;
        }
        memcpy(mtk_last_rec[i].p, p, n);
        mtk_last_rec[i].len = n;
        mtk_last_rec[i].code = code;
        return;
    }
}

/* A decoded struct as JSON: fields by name, arrays for counts other than a fixed 1
 * ("Reserved" fields left out). */
static size_t mtk_json(char *out, size_t cap, size_t o, const struct mtk_node *n, int depth) {
    const struct mtk_table *t = &MTK_TABLES[n->table];
    MPUT("{");
    int first = 1;
    for (int i = 0; i < t->rows && depth < 12; i++) {
        const struct mtk_row *r = &MTK_ROWS[t->first + i];
        if (!strncmp(mtk_name(r), "Reserved", 8)) continue;
        long count = mtk_count(n, r);
        if (count < 0) continue;
        MPUT("%s\"", first ? "" : ",");
        for (const char *c = mtk_name(r); *c; c++) MPUT(*c == '"' || *c == '\\' ? "\\%c" : "%c", *c);
        MPUT("\":");
        first = 0;
        int list = r->count != 1;
        if (list) MPUT("[");
        if (r->prim) {
            int w = mtk_prim_width(r, count);
            for (long k = 0; k < count && k < 4096; k++) {
                int64_t v;
                if (!mtk_get_bits(n, n->base + r->off + (uint32_t)(k * w), w, mtk_signed(r), &v)) break;
                MPUT("%s%lld", k ? "," : "", (long long)v);
            }
        } else {
            struct mtk_node items[64];
            int k = mtk_item_nodes(n, r, items, 64, NULL);
            for (int j = 0; j < k; j++) { if (j) MPUT(","); o = mtk_json(out, cap, o, &items[j], depth + 1); }
        }
        if (list) MPUT("]");
    }
    MPUT("}");
    return o;
}

/* {"ok":true,"code":"0x9001","version":N,"fields":{...}} for the last record of `code`. */
static int mtk_log_json(char *out, size_t cap, uint16_t code) {
    size_t o = 0;
    pthread_mutex_lock(&lock);
    for (size_t i = 0; i < sizeof mtk_last_rec / sizeof mtk_last_rec[0]; i++) {
        struct mtk_node root;
        if (mtk_last_rec[i].code != code || !mtk_open_record(code, mtk_last_rec[i].p, mtk_last_rec[i].len, &root)) continue;
        MPUT("{\"ok\":true,\"code\":\"0x%04X\",\"version\":%d,\"fields\":", code, mtk_last_rec[i].p[0]);
        o = mtk_json(out, cap, o, &root, 0);
        MPUT("}\n");
        pthread_mutex_unlock(&lock);
        return o < cap ? (int)o : snprintf(out, cap, "{\"ok\":false,\"error\":\"record too large\"}\n");
    }
    pthread_mutex_unlock(&lock);
    return snprintf(out, cap, "{\"ok\":false,\"error\":\"no 0x%04X record yet\"}\n", code);
}

static void mtk_log(int kind, const uint8_t *rec, size_t n) {
    size_t at = kind == MTK_RECORD ? 0x14 : 0x10;
    if (n <= at) return;
    uint16_t code = (uint16_t)le16(rec + 6);
    struct mtk_node root;
    if (!mtk_open_record(code, rec + at, n - at, &root)) return;
    long now = now_ms();
    pthread_mutex_lock(&lock);
    mtk_keep(code, rec + at, n - at);
    mtk_last_log = now;
    mtk_logs++;
    mtk_codes_seen[kind == MTK_EVENT]++;
    if (code == MTK_NR_RRC_PDU) mtk_rrc_event(&root);
    else if (code >= 0x9000) mtk_nr_log(code, &root, now);
    else mtk_lte_log(code, &root, now);
    pthread_mutex_unlock(&lock);
}

