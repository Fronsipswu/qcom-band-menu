static const uint8_t MTK_DISCONNECT[4] = { 0x05, 0x00, 0x00, 0x00 };

/* ICD filter ranges of this modem (FM350): record codes and event codes. */
static const uint16_t MTK_RECORD_RANGES[][2] = { { 0x7000, 0x7201 }, { 0x9000, 0x9180 }, { 0x2000, 0x2000 },
                                                 { 0x2300, 0x2300 }, { 0xF000, 0xF200 } };
static const uint16_t MTK_EVENT_RANGES[][2] = { { 0x7500, 0x7708 }, { 0x9500, 0x9692 }, { 0x2200, 0x2243 },
                                                { 0xF500, 0xF700 } };
static const uint16_t MTK_RECORDS[] = { MTK_RECORD_CODES };
static const uint16_t MTK_EVENTS[] = { MTK_EVENT_CODES };

/* ICD set filter (cmd 7) for [start, end] with exactly `codes` on: 0F 00 type u16 start
 * u16 end, then an LSB-first bitmap of (end - start + 8) / 8 bytes. */
static size_t mtk_set_filter(uint8_t seq, uint8_t type, uint16_t start, uint16_t end, const uint16_t *codes, int ncodes) {
    uint8_t p[7 + 1024];
    size_t nbytes = (size_t)(end - start + 8) >> 3;
    if (nbytes > 1024) return 0;
    p[0] = 0x0F; p[1] = 0; p[2] = type; put16(p + 3, start); put16(p + 5, end);
    memset(p + 7, 0, nbytes);
    for (int i = 0; i < ncodes; i++)
        if (codes[i] >= start && codes[i] <= end) p[7 + ((codes[i] - start) >> 3)] |= (uint8_t)(1u << ((codes[i] - start) & 7));
    return mtk_icd(7, seq, p, 7 + nbytes);
}

/* ── Trace filters ───────────────────────────────────────────────────────── */

enum { MTK_T_PS, MTK_T_L1, MTK_T_NR, MTK_T_SAP, MTK_T_MOD, MTK_TABLES_N };
static const struct { const char *name; uint32_t dump_code; uint32_t size; uint8_t cmd; const uint8_t *orig; } MTK_TRACE[] = {
    /* in the order they were tested */
    { "ps-traces", 0x01100018, 16016, 0x09, MTK_TRACE_ORIG_09 },
    { "mcu-l1", 0x0110001A, 2256, 0x0A, MTK_TRACE_ORIG_0A },
    { "nr-dsp", 0x01100021, 128, 0x0E, MTK_TRACE_ORIG_NR },
    { "primitive-saps", 0x01100019, 1950, 0x06, MTK_TRACE_ORIG_06 },
    { "primitive-modules", 0x01100017, 251, 0x05, MTK_TRACE_ORIG_05 },
};

/* The NR DSP filter goes in as an injected ILM message (wire cmd 0x0E) to DHL's DSP filter
 * handler (src/dst module 17, SAP 4, message 0x2008), local parameter 0x808 bytes: u8 1, u8 0,
 * u16 0x808, u8 type 2, u8 source 1, u16 64, then 64 entries (u8 module, 3 pad, u32 mask).
 * The handler saves all 0x808 bytes, so the whole buffer is sent. */
static size_t mtk_nr_filter(const uint8_t *masks) {
    static uint8_t p[5 + 32 + 1 + 0x808];
    memset(p, 0, sizeof p);
    p[0] = 0x00; p[1] = 0x08; p[2] = 0x00; p[3] = 0x0C; p[4] = 0x00;   /* local/peer length offsets */
    uint8_t *h = p + 5;
    put16(h, 17); put16(h + 2, 17); put16(h + 4, 4); put16(h + 6, 0x2008);
    put32(h + 8, 0x808);                                             /* local length; peer 0 */
    uint8_t *local = p + 5 + 32 + 1;                                 /* after a zero pointer count */
    local[0] = 1; local[1] = 0; put16(local + 2, 0x808); local[4] = 2; local[5] = 1; put16(local + 6, 64);
    for (int m = 0; m < 64; m++) {
        local[8 + 8 * m] = (uint8_t)m;
        put32(local + 12 + 8 * m, masks[m]);
    }
    return mtk_host(0x0E, p, sizeof p);
}

/* The setter frame that leaves table t as `content` (size bytes; NR: 128 masks). */
static size_t mtk_trace_packet(int t, const uint8_t *content) {
    return t == MTK_T_NR ? mtk_nr_filter(content) : mtk_host(MTK_TRACE[t].cmd, content, MTK_TRACE[t].size);
}

