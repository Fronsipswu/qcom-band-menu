static long mtk_window_start;


static void mtk_common(char *out, size_t cap, size_t *op, struct mtk_carrier *s, long now) {
    size_t o = *op;
    for (int k = 0; k < MQ_N; k++) {
        double v;
        /* The RRC measurement (0x9101) is the cell-level SS-RSRQ; prefer it
         * over the L1 beam mean while it is fresh. */
        if (k == MQ_RSRQ && mh_get(&s->rrc_rsrq, now, &v)) { MPUT(",\"%s\":%.2f", MQ_KEY[k], v); continue; }
        if (mm_get(&s->q[k], &v)) mh_put(&s->hq[k], v, now);
        if (mh_get(&s->hq[k], now, &v)) MPUT(",\"%s\":%.2f", MQ_KEY[k], v);
    }
    for (int k = 0; k < MC_N; k++) {
        double v[4]; int have = 0, got[4];
        for (int c = 0; c < 4; c++) {
            if (mm_get(&s->chain[k][c], &v[c])) mh_put(&s->hchain[k][c], v[c], now);
            got[c] = mh_get(&s->hchain[k][c], now, &v[c]);
            have |= got[c];
        }
        if (!have) continue;
        MPUT(",\"%s\":[", MC_KEY[k]);
        for (int c = 0; c < 4; c++) { if (got[c]) MPUT("%s%.2f", c ? "," : "", v[c]); else MPUT("%snull", c ? "," : ""); }
        MPUT("]");
    }
    *op = o;
}

static int mtk_argmax(const long *v, int n) {
    int b = -1;
    for (int i = 0; i < n; i++) if (v[i] && (b < 0 || v[i] > v[b])) b = i;
    return b;
}

static size_t mtk_nr_json(char *out, size_t cap, size_t o, int cc, long now, long ms, int *first) {
    struct mtk_nr_cfg *c = &mtk_nr_cfg[cc];
    struct mtk_carrier *s = &mtk_nr[cc];
    double v;
    int have_last = 0;
    for (int k = 0; k < ML_N; k++) if (mh_get(&s->last[k], now, &v)) have_last = 1;
    int have_held = 0;
    for (int k = 0; k < MQ_N; k++) if (s->hq[k].at && now - s->hq[k].at < MTK_HOLD_MS) have_held = 1;
    if (s->rrc_rsrq.at && now - s->rrc_rsrq.at < MTK_HOLD_MS) have_held = 1;
    if (!c->known && !s->any && !have_last && !have_held && !s->dl_tbs && !s->ul_tbs) return o;
    MPUT("%s{\"cc\":%d,\"pcell\":%s", *first ? "" : ",", cc, cc == 0 ? "true" : "false");
    *first = 0;
    if (c->known) {
        MPUT(",\"pci\":%d,\"arfcn\":%u,\"dl_arfcn\":%u", c->pci, (unsigned)c->arfcn, (unsigned)c->arfcn);
        if (c->band) MPUT(",\"band\":%d", c->band);
        if (c->bw) MPUT(",\"bw\":%d", c->bw);
        if (c->scs) MPUT(",\"scs\":%d", c->scs);
        if (c->max_layers) MPUT(",\"max_layers\":%d", c->max_layers);
        int ports = rrc_csi_ports(c->pci, c->arfcn, cc == 0);
        if (ports) MPUT(",\"csi_ports\":%d", ports);
    }
    mtk_common(out, cap, &o, s, now);
    if (mh_get(&s->last[ML_CQI], now, &v)) {
        MPUT(",\"cqi\":%d", (int)v);
        if (mh_get(&s->last[ML_RI], now, &v)) MPUT(",\"ri\":%d", (int)v);
    }
    MPUT(",\"tb\":%d", mh_get(&s->last[ML_TB], now, &v) ? (int)v : 0);
    if (mh_get(&s->last[ML_MBPS], now, &v)) {
        MPUT(",\"mbps\":%.3f", v);
        if (mh_get(&s->last[ML_MBPS_SCHED], now, &v)) MPUT(",\"mbps_sched\":%.3f", v);
    }
    if (mh_get(&s->last[ML_BLER], now, &v)) MPUT(",\"bler\":%.2f", v);
    if (mh_get(&s->last[ML_UL_MBPS], now, &v)) MPUT(",\"ul_mbps\":%.3f", v);
    if (mh_get(&s->last[ML_UL_BLER], now, &v)) MPUT(",\"ul_bler\":%.2f", v);
    /* TB counting (not qbm-diagd keys; for comparison): the PCell's, all carriers' TBs */
    if (s->dl_tbs) MPUT(",\"mbps_tb\":%.3f", (double)s->dl_tb_bytes * 8 / ((double)ms * 1000));
    if (s->ul_tbs) MPUT(",\"ul_mbps_tb\":%.3f", (double)s->ul_tb_bytes * 8 / ((double)ms * 1000));
    for (int k = 0; k < MD_N; k++) if (mm_get(&s->d[k], &v)) MPUT(",\"%s\":%.2f", MD_KEY[k], v);
    if (mm_get(&s->d[MD_MCS], &v)) MPUT(",\"mcs_all\":%.2f", v);
    int m = mtk_argmax(s->mod, 5);
    if (m >= 0) MPUT(",\"mod\":\"%s\"", MTK_MOD[m]);
    put_pct(out, cap, &o, "mod_pct", s->mod, 5);           /* per DCI: QPSK..1024QAM */
    m = mtk_argmax(s->ul_mod, 6);
    if (m >= 0) MPUT(",\"ul_mod\":\"%s\"", MTK_UL_MOD[m]);
    put_pct(out, cap, &o, "ul_mod_pct", s->ul_mod, 6);     /* BPSK..1024QAM */
    /* qbm-diagd's TX mode comes from Qualcomm's PUSCH TX mode; here derived: two or more
     * layers -> SMDL, one layer precoded over 2+ SRS ports (codebook) -> SMSL, else SISO */
    if (mm_get(&s->d[MD_UL_LAYERS], &v))
        MPUT(",\"ul_tx_mode\":\"%s\"", v >= 1.5 ? "SMDL" : c->codebook && c->srs_ports >= 2 ? "SMSL" : "SISO");
    int rx = 0;
    for (int ch = 0; ch < 4; ch++) {
        double x;
        if (mh_get(&s->hchain[MC_CSINR][ch], now, &x) || mh_get(&s->hchain[MC_CRSRP][ch], now, &x)
            || mh_get(&s->hchain[MC_TRSRP][ch], now, &x)) rx++;
    }
    if (rx) MPUT(",\"rx\":%d", rx);
    MPUT("}");
    return o;
}

static size_t mtk_lte_json(char *out, size_t cap, size_t o, int slot, long now, long ms, int *first) {
    struct mtk_lte_cfg *c = &mtk_lte_cfg[slot];
    struct mtk_carrier *s = &mtk_lte[slot];
    double v, b0, b1;
    size_t start = o;
    MPUT("%s{\"slot\":%d", *first ? "" : ",", slot);
    size_t bare = o;
    if (c->known) {
        if (c->earfcn) MPUT(",\"earfcn\":%u", (unsigned)c->earfcn);
        MPUT(",\"pci\":%d", c->pci);
        if (c->state) MPUT(",\"state\":%d", c->state);
        if (c->band) MPUT(",\"band\":%d", c->band);
        if (c->bw > 0) MPUT(",\"bw\":%.1f", c->bw);
        if (c->tm) MPUT(",\"tm\":%d", c->tm);
    }
    mtk_common(out, cap, &o, s, now);
    int h0 = mh_get(&s->last[ML_MBPS0], now, &b0), h1 = mh_get(&s->last[ML_MBPS1], now, &b1);
    if (s->dl_tbs) {
        /* PHY throughput from the counted TBs, as qbm-diagd does on Qualcomm:
         * CRC-passed bytes over the window, and every scheduled byte. */
        MPUT(",\"tb\":%ld,\"mbps\":%.3f,\"mbps_sched\":%.3f,\"bler\":%.2f", s->dl_tbs,
             (double)s->dl_tb_bytes * 8 / ((double)ms * 1000),
             (double)(s->dl_tb_bytes_all ? s->dl_tb_bytes_all : s->dl_tb_bytes) * 8 / ((double)ms * 1000),
             100.0 * (double)s->dl_tb_fail / (double)s->dl_tbs);
    } else if (h0 || h1) {
        /* fallback: the modem's throughput summary logs */
        MPUT(",\"mbps\":%.3f", (h0 ? b0 : 0) + (h1 ? b1 : 0));
        double l0, l1;
        int g0 = mh_get(&s->last[ML_BLER0], now, &l0), g1 = mh_get(&s->last[ML_BLER1], now, &l1);
        if (g0 || g1) MPUT(",\"bler\":%.2f", g0 && g1 ? (l0 > l1 ? l0 : l1) : g0 ? l0 : l1);
        double t0 = 0, t1 = 0;
        mh_get(&s->last[ML_TB0], now, &t0); mh_get(&s->last[ML_TB1], now, &t1);
        MPUT(",\"tb\":%d", (int)(t0 + t1));
    }
    if (s->ul_tbs) MPUT(",\"ul_mbps\":%.3f", (double)s->ul_tb_bytes * 8 / ((double)ms * 1000));
    else if (mh_get(&s->last[ML_UL_MBPS], now, &v)) MPUT(",\"ul_mbps\":%.3f", v);
    if (mh_get(&s->last[ML_UL_BLER], now, &v)) MPUT(",\"ul_bler\":%.2f", v);
    for (int k = 0; k < MD_N; k++) if (mm_get(&s->d[k], &v)) MPUT(",\"%s\":%.2f", MD_KEY[k], v);
    int m = mtk_argmax(s->mod, 5);
    if (m >= 0) MPUT(",\"mod\":\"%s\"", MTK_MOD[m]);
    put_pct(out, cap, &o, "mod_pct", s->mod, 5);            /* per TB: QPSK..1024QAM */
    m = mtk_argmax(s->ul_mod, 6);
    if (m >= 0) MPUT(",\"ul_mod\":\"%s\"", MTK_UL_MOD[m]);
    put_pct(out, cap, &o, "ul_mod_pct", s->ul_mod, 6);      /* BPSK..1024QAM */
    if (mh_get(&s->last[ML_CQI], now, &v)) MPUT(",\"cqi\":%d", (int)v);
    if (mh_get(&s->last[ML_RANK], now, &v)) MPUT(",\"rank\":%d", (int)v);
    /* The MIB (0x7104 / 0x700C) and the SCell reconfiguration (0x7102) name
     * the eNB's TX antenna count per PCI+EARFCN. No stream-count fallback:
     * that produced a bogus "3" from the mean layer count. */
    int tx = (c->earfcn && c->pci >= 0) ? mtk_lte_tx_get(c->earfcn, c->pci) : 0;
    if (tx) MPUT(",\"tx\":%d", tx);
    /* LTE RX chain count is deliberately not reported for now. */
    if (o == bare) return start;                 /* nothing but the slot: leave it out */
    MPUT("}");
    *first = 0;
    return o;
}

static int write_stats_mtk(char *out, size_t cap, int for_sim) {
    size_t o = 0;
    pthread_mutex_lock(&lock);
    long now = now_ms(), ms = now - mtk_window_start;
    if (ms < 1) ms = 1;
    mtk_lte_expire(now);
    int silent = !mtk_last_log || now - mtk_last_log > SILENT_MS;
    int lte_known = 0;
    for (int i = 0; i < MTK_CC; i++) lte_known |= mtk_lte_cfg[i].known;
    MPUT("{\"ok\":true,\"version\":\"%s\",\"lib\":\"mtk-icd\",\"ms\":%ld,\"logs\":%ld,\"sim\":%d,\"sim_tags\":false,\"ca_known\":%s,\"carriers\":[",
         HELPER_VERSION, ms, mtk_logs, for_sim == 2 ? 2 : 1, lte_known ? "true" : "false");
    int first = 1, any_lte = 0, any_nr = 0;
    if (!silent && for_sim != 2)
        for (int i = 0; i < MTK_CC; i++) { size_t before = o; o = mtk_lte_json(out, cap, o, i, now, ms, &first); any_lte |= o != before; }
    MPUT("],\"nr\":[");
    first = 1;
    if (!silent && for_sim != 2)
        for (int i = 0; i < MTK_CC; i++) { size_t before = o; o = mtk_nr_json(out, cap, o, i, now, ms, &first); any_nr |= o != before; }
    MPUT("]");
    if (!silent && for_sim != 2) {
        int nfirst = 1;
        for (int j = 0; j < MTK_NB_MAX; j++) {
            if (!mtk_nb[j].known || now - mtk_nb[j].at >= MTK_HOLD_MS) continue;
            MPUT("%s[%u,%d,%d,%.1f,%.1f]", nfirst ? ",\"nr_nb\":[" : ",", (unsigned)mtk_nb[j].arfcn, mtk_nb[j].pci, mtk_nb[j].ssb,
                 mtk_nb[j].rsrp, mtk_nb[j].rsrq);
            nfirst = 0;
        }
        if (!nfirst) MPUT("]");
    }
    if (any_lte && mtk_ta_lte >= 0) MPUT(",\"lte_ta\":%d", mtk_ta_lte);
    if (any_nr && mtk_ta_nr >= 0) MPUT(",\"nr_ta\":%d", mtk_ta_nr);
    MPUT("}\n");
    /* a new window */
    mtk_window_start = now;
    mtk_logs = 0;
    for (int i = 0; i < MTK_CC; i++) {
        struct mtk_carrier *s[2] = { &mtk_nr[i], &mtk_lte[i] };
        for (int k = 0; k < 2; k++) {
            memset(s[k]->q, 0, sizeof s[k]->q); memset(s[k]->d, 0, sizeof s[k]->d); memset(s[k]->chain, 0, sizeof s[k]->chain);
            memset(s[k]->mod, 0, sizeof s[k]->mod); memset(s[k]->ul_mod, 0, sizeof s[k]->ul_mod);
            s[k]->dl_tb_bytes = s[k]->dl_tb_bytes_all = s[k]->dl_tb_fail = 0;
            s[k]->ul_tb_bytes = s[k]->dl_tbs = s[k]->ul_tbs = 0;
            s[k]->any = 0;
        }
    }
    pthread_mutex_unlock(&lock);
    return o < cap ? (int)o : -1;
}

/* ── Receive side: mux frames, then DHL records on channel 0x10 ──────────── */

static uint8_t *mtk_raw, *mtk_main;
static size_t mtk_raw_len, mtk_main_len, mtk_raw_cap = MTK_FRAME_MAX + 65536, mtk_main_cap = MTK_FRAME_MAX + 65536;
static int mtk_synced, mtk_dhl_synced;
static long mtk_bytes, mtk_frames, mtk_resyncs;

/* Trace filter state of this connection. */
static struct {
    int seen[MTK_TABLES_N];                 /* dumped since the last connect */
    uint8_t *table[MTK_TABLES_N];
    int firmware_ok;                        /* ICD version reply names MTK_FIRMWARE */
    char firmware[48];
    int dumped;                             /* a dump since the last connect */
} mtk_tf;

static int mtk_is_kind(uint8_t k) { return k == 0x11 || k == 0x12 || k == 0x13 || k == 0x15 || k == 0x17 || k == 0x20; }

static void mtk_dhl_record(const uint8_t *rec, size_t n) {
    uint8_t kind = rec[0];
    if (kind == MTK_RECORD || kind == MTK_EVENT) { mtk_log(kind, rec, n); return; }
    if (kind == MTK_ICD_REPLY && n > 12) {
        /* the version reply (cmd 1) carries the firmware as text */
        const uint8_t *hit = memmem(rec, n, "81600.", 6);
        if (hit) {
            size_t k = 0;
            while (hit + k < rec + n && k < sizeof mtk_tf.firmware - 1 && hit[k] > 0x20 && hit[k] < 0x7F && hit[k] != '"' && hit[k] != '\\') k++;
            memcpy(mtk_tf.firmware, hit, k);
            mtk_tf.firmware[k] = 0;
            mtk_tf.firmware_ok = !strcmp(mtk_tf.firmware, MTK_FIRMWARE);
        }
        return;
    }
    if (kind == MTK_KIND_TRACE && n >= 16 && rec[4] == 0x00 && rec[5] == 0x02 && rec[6] == 0xF8 && rec[7] == 0xFA) {
        uint32_t code = le32(rec + 8);
        for (int t = 0; t < MTK_TABLES_N; t++) {
            if (code != MTK_TRACE[t].dump_code || n != MTK_TRACE[t].size + 16) continue;
            if (!mtk_tf.table[t]) mtk_tf.table[t] = malloc(MTK_TRACE[t].size);
            if (!mtk_tf.table[t]) return;
            memcpy(mtk_tf.table[t], rec + 16, MTK_TRACE[t].size);
            mtk_tf.seen[t] = 1;
            mtk_tf.dumped = 1;
        }
    }
}

static void mtk_dhl_pump(void) {
    size_t j = 0;
    uint8_t *m = mtk_main;
    while (j + 4 <= mtk_main_len) {
        size_t n = (size_t)m[j + 1] | (size_t)m[j + 2] << 8 | (size_t)m[j + 3] << 16;
        if (!mtk_is_kind(m[j]) || n < 8) {
            if (mtk_dhl_synced) mtk_resyncs++;
            mtk_dhl_synced = 0;
            j++;
            continue;
        }
        if (j + n > mtk_main_len) break;
        if (!mtk_dhl_synced) {
            /* trust a header only when the next one looks right too */
            if (j + n + 4 > mtk_main_len) break;
            if (!mtk_is_kind(m[j + n])) { j++; continue; }
            mtk_dhl_synced = 1;
        }
        mtk_dhl_record(m + j, n);
        j += n;
    }
    memmove(m, m + j, mtk_main_len - j);
    mtk_main_len -= j;
}

static int mtk_header(size_t i, uint32_t *len, uint32_t *flags) {
    if (i + 16 > mtk_raw_len) return 0;
    uint32_t a = le32(mtk_raw + i), n = le32(mtk_raw + i + 4), f = le32(mtk_raw + i + 8), x = le32(mtk_raw + i + 12);
    if (a != MTK_MAGIC || x != (a ^ n ^ f) || n > MTK_FRAME_MAX) return 0;
    *len = n; *flags = f;
    return 1;
}

static void mtk_feed(const uint8_t *p, size_t n) {
    mtk_bytes += (long)n;
    while (n) {
        size_t take = mtk_raw_cap - mtk_raw_len;
        if (take > n) take = n;
        memcpy(mtk_raw + mtk_raw_len, p, take);
        mtk_raw_len += take; p += take; n -= take;
        for (;;) {
            uint32_t len, flags;
            if (!mtk_synced) {
                /* a frame header (XOR-checked) followed by another, or by not enough bytes yet */
                size_t i = 0;
                int found = 0;
                for (; i + 16 <= mtk_raw_len; i++) {
                    if (le32(mtk_raw + i) != MTK_MAGIC || !mtk_header(i, &len, &flags)) continue;
                    uint32_t l2, f2;
                    if (i + 16 + len + 16 > mtk_raw_len || mtk_header(i + 16 + len, &l2, &f2)) { found = 1; break; }
                }
                if (!found) {
                    /* keep the last 15 bytes: a header may start there */
                    size_t from = mtk_raw_len > 15 ? mtk_raw_len - 15 : 0;
                    memmove(mtk_raw, mtk_raw + from, mtk_raw_len - from);
                    mtk_raw_len -= from;
                    break;
                }
                if (i) { mtk_resyncs++; memmove(mtk_raw, mtk_raw + i, mtk_raw_len - i); mtk_raw_len -= i; }
                mtk_synced = 1;
            }
            if (!mtk_header(0, &len, &flags)) {
                if (mtk_raw_len < 16) break;
                mtk_synced = 0;
                memmove(mtk_raw, mtk_raw + 1, mtk_raw_len - 1);
                mtk_raw_len--;
                continue;
            }
            if (mtk_raw_len < 16 + (size_t)len) break;
            if (flags == MTK_MAIN) {
                if (mtk_main_len + len > mtk_main_cap) { mtk_main_len = 0; mtk_dhl_synced = 0; }
                memcpy(mtk_main + mtk_main_len, mtk_raw + 16, len);
                mtk_main_len += len;
                mtk_dhl_pump();
            }
            mtk_frames++;
            memmove(mtk_raw, mtk_raw + 16 + len, mtk_raw_len - 16 - len);
            mtk_raw_len -= 16 + len;
        }
    }
}

static void mtk_reset_stream(void) {
    mtk_raw_len = mtk_main_len = 0;
    mtk_synced = mtk_dhl_synced = 0;
    for (int t = 0; t < MTK_TABLES_N; t++) mtk_tf.seen[t] = 0;
    mtk_tf.dumped = 0;
}

static int mtk_init(void) {
    if (mtk_raw) return 1;
    mtk_raw = malloc(mtk_raw_cap);
    mtk_main = malloc(mtk_main_cap);
    mtk_window_start = now_ms();
    mtk_lte_slots_reset();
    return mtk_raw && mtk_main;
}

/* ── The session: connect, enable ICD, trace filters, watchdog ───────────── */

static int mtk_trim = 1;                    /* -mtk-trim: trim the trace filters */
static int mtk_restore_pending;             /* "Restore MTK DIAG profile" asked for */
static char mtk_trace_state[160] = "unknown";
static long mtk_trace_written;

static int mtk_send(int fd, size_t n) { return n && tty_write_all(fd, mtk_tx, n) == 0 ? 0 : -1; }

static void mtk_enable_icd(int fd) {
    uint8_t seq = 0;
    mtk_send(fd, mtk_icd(1, seq++, NULL, 0));          /* query version: names the firmware */
    usleep(50 * 1000);
    /* every record range: codes not decoded here go off (the filters persist in the modem) */
    for (size_t r = 0; r < sizeof MTK_RECORD_RANGES / sizeof MTK_RECORD_RANGES[0]; r++) {
        mtk_send(fd, mtk_set_filter(seq++, 1, MTK_RECORD_RANGES[r][0], MTK_RECORD_RANGES[r][1], MTK_RECORDS,
                                    (int)(sizeof MTK_RECORDS / sizeof MTK_RECORDS[0])));
        usleep(50 * 1000);
    }
    /* events: only the ranges holding the ones decoded here */
    for (size_t r = 0; r < sizeof MTK_EVENT_RANGES / sizeof MTK_EVENT_RANGES[0]; r++) {
        int any = 0;
        for (size_t i = 0; i < sizeof MTK_EVENTS / sizeof MTK_EVENTS[0]; i++)
            if (MTK_EVENTS[i] >= MTK_EVENT_RANGES[r][0] && MTK_EVENTS[i] <= MTK_EVENT_RANGES[r][1]) any = 1;
        if (!any) continue;
        mtk_send(fd, mtk_set_filter(seq++, 0, MTK_EVENT_RANGES[r][0], MTK_EVENT_RANGES[r][1], MTK_EVENTS,
                                    (int)(sizeof MTK_EVENTS / sizeof MTK_EVENTS[0])));
        usleep(50 * 1000);
    }
}

/* After the connect dump window: writes the tables that differ from the target (trim: all
 * zero; restore: the originals), each at most once per run. A trimmed modem sends no dump,
 * so trim never writes blind; restore with no dump at all writes every original. */
/* What the tables are now: as dumped on connect, updated with what this run wrote since. */
static void mtk_trace_summary(char *state, size_t cap) {
    static const uint8_t zero[16016];
    int differ = 0, trimmed = 0, original = 0;
    for (int t = 0; t < MTK_TABLES_N; t++) {
        if (!mtk_tf.seen[t]) continue;
        if (!memcmp(mtk_tf.table[t], zero, MTK_TRACE[t].size)) trimmed++;
        else if (!memcmp(mtk_tf.table[t], MTK_TRACE[t].orig, MTK_TRACE[t].size)) original++;
        else differ++;
    }
    if (!mtk_tf.dumped) snprintf(state, cap, "trimmed (no table dump on connect)");
    else snprintf(state, cap, "%d trimmed, %d original, %d other", trimmed, original, differ);
}

static void mtk_trace_apply(int fd) {
    static int written[2][MTK_TABLES_N];
    static uint8_t zero[16016];
    int restore = mtk_restore_pending;
    char state[160] = "";
    mtk_trace_summary(state, sizeof state);
    if (!restore && !mtk_trim) { snprintf(mtk_trace_state, sizeof mtk_trace_state, "%s; trim off", state); return; }
    if (!mtk_tf.firmware_ok) {
        snprintf(mtk_trace_state, sizeof mtk_trace_state, "%s; not written: firmware %s is not %s", state,
                 mtk_tf.firmware[0] ? mtk_tf.firmware : "unknown", MTK_FIRMWARE);
        if (restore) mtk_restore_pending = 0;
        return;
    }
    int sent = 0, nodump = !mtk_tf.dumped;
    for (int t = 0; t < MTK_TABLES_N; t++) {
        const uint8_t *target = restore ? MTK_TRACE[t].orig : zero;
        if (restore && nodump) {
            /* trimmed: no dump to compare against */
        } else if (!mtk_tf.seen[t] || !memcmp(mtk_tf.table[t], target, MTK_TRACE[t].size)) {
            continue;
        } else if (t == MTK_T_NR && memcmp(mtk_tf.table[t] + 64, zero, 64)) {
            continue;                       /* modules 64-127 active: the packet covers 0-63 */
        }
        if (written[restore][t]) continue;
        written[restore][t] = 1;
        if (mtk_send(fd, mtk_trace_packet(t, target)) == 0) {
            sent++;
            mtk_trace_written++;
            /* the modem has `target` now (it dumps again only on the next connect) */
            if (!mtk_tf.table[t]) mtk_tf.table[t] = malloc(MTK_TRACE[t].size);
            if (mtk_tf.table[t]) { memcpy(mtk_tf.table[t], target, MTK_TRACE[t].size); mtk_tf.seen[t] = 1; mtk_tf.dumped = 1; }
        }
        usleep(100 * 1000);
    }
    if (restore) {
        mtk_restore_pending = 0;
        mtk_trim = 0;                       /* don't trim again in this run */
        memset(written, 0, sizeof written); /* a later Restore or trim may write again */
    }
    mtk_trace_summary(state, sizeof state);
    snprintf(mtk_trace_state, sizeof mtk_trace_state, "%s; %s: %d table%s written", state, restore ? "restore" : "trim",
             sent, sent == 1 ? "" : "s");
}

static char mtk_dev[64] = "";

/* The FM350's debug port: USB interface 09 of a MediaTek (0e8d) device. */
static int mtk_find_port(char *dev, size_t cap) {
    for (int i = 0; i < USB_PROBE_MAX; i++) {
        char p[96], v[16];
        snprintf(p, sizeof p, "/sys/class/tty/ttyUSB%d/device/../bInterfaceNumber", i);
        FILE *f = fopen(p, "r");
        if (!f) continue;
        int ok = fgets(v, sizeof v, f) && strtol(v, NULL, 16) == 9;
        fclose(f);
        if (!ok) continue;
        snprintf(p, sizeof p, "/sys/class/tty/ttyUSB%d/device/../../idVendor", i);
        f = fopen(p, "r");
        if (!f) continue;
        ok = fgets(v, sizeof v, f) && !strncmp(v, "0e8d", 4);
        fclose(f);
        if (ok) { snprintf(dev, cap, "/dev/ttyUSB%d", i); return 1; }
    }
    return 0;
}

static int mtk_open(const char *want) {
    char dev[64], msg[160];
    if (!mtk_init()) { note("out of memory"); return -1; }
    if (strcmp(want, "auto")) snprintf(dev, sizeof dev, "%s", want);
    else if (!mtk_find_port(dev, sizeof dev)) { note("FM350: no debug port (USB interface 09) found (retrying)"); return -1; }
    int fd = open(dev, O_RDWR | O_NOCTTY | O_NONBLOCK | O_CLOEXEC);
    if (fd < 0) { snprintf(msg, sizeof msg, "open %s: %s (retrying)", dev, strerror(errno)); note(msg); return -1; }
    struct termios t;
    if (tcgetattr(fd, &t) == 0) {
        cfmakeraw(&t);
        t.c_cflag |= CLOCAL | CREAD;
        t.c_cc[VMIN] = 1;
        t.c_cc[VTIME] = 0;
        tcsetattr(fd, TCSANOW, &t);
    }
    tcflush(fd, TCIOFLUSH);
    snprintf(mtk_dev, sizeof mtk_dev, "%s", dev);
    snprintf(active_dev, sizeof active_dev, "%s", dev);
    snprintf(msg, sizeof msg, "FM350: debug port %s", dev);
    note(msg);
    return fd;
}

/* One connection's progress (connect, ICD enable, trace filters) and the watchdog. */
static struct { long connected_at, last_rx, icd_at; int enabled, traced, reconnects, icd_on; } mtk_s;

static void mtk_connect(int fd) {
    mtk_reset_stream();
    mtk_send(fd, mtk_host(0x2E, MTK_CONNECT, sizeof MTK_CONNECT));
    mtk_s.connected_at = mtk_s.last_rx = now_ms();
    mtk_s.enabled = mtk_s.traced = 0;
}

/* Reads the port and drives the session; -1 when the port is gone. */
static int mtk_pump(int fd) {
    uint8_t buf[65536];
    for (;;) {
        ssize_t k = read(fd, buf, sizeof buf);
        if (k > 0) { mtk_s.last_rx = now_ms(); mtk_feed(buf, (size_t)k); continue; }
        if (k < 0 && (errno == EAGAIN || errno == EINTR)) break;
        return -1;
    }
    return 0;
}

static void mtk_tick(int fd) {
    long now = now_ms();
    if (!mtk_s.enabled && now - mtk_s.connected_at > 300) {
        /* ICD filters once per run (they persist in the modem); a reconnect only connects */
        if (!mtk_s.icd_on) { mtk_enable_icd(fd); mtk_s.icd_on = 1; mtk_s.icd_at = now; }
        else mtk_send(fd, mtk_icd(1, 0, NULL, 0));
        mtk_s.enabled = 1;
    }
    int all = 1;
    for (int t = 0; t < MTK_TABLES_N; t++) all &= mtk_tf.seen[t];
    if (mtk_s.enabled && !mtk_s.traced && (all || now - mtk_s.connected_at > MTK_DUMP_WAIT_MS)) {
        mtk_trace_apply(fd);
        mtk_s.traced = 1;
    }
    if (mtk_restore_pending && mtk_s.traced) mtk_trace_apply(fd);
    if (now - mtk_s.last_rx > MTK_SILENT_S * 1000) {
        /* the modem stops logging when it falls behind; a fresh connect restarts it, and a
         * second silence enables ICD again (at most once a minute: the filters may be
         * saved in the modem too) */
        mtk_s.reconnects++;
        if (mtk_s.reconnects % 2 == 0 && now - mtk_s.icd_at > 60000) mtk_s.icd_on = 0;
        mtk_connect(fd);
    }
}

static int mtk_status(char *msg, size_t cap, int open) {
    return snprintf(msg, cap, "{\"ok\":true,\"version\":\"%s\",\"modem\":\"mtk\",\"dev\":\"%s\",\"port_open\":%s,\"frames\":%ld,"
                    "\"bytes\":%ld,\"resyncs\":%ld,\"reconnects\":%d,\"firmware\":\"%s\",\"trim\":%s,\"trace\":\"%s\"}\n",
                    HELPER_VERSION, mtk_dev, open ? "true" : "false", mtk_frames, mtk_bytes, mtk_resyncs, mtk_s.reconnects,
                    mtk_tf.firmware, mtk_trim ? "true" : "false", mtk_trace_state);
}

/* Offline checks: the trace filter packets, for comparing with the live-tested ones. */
static int mtk_dump_packets(const char *dir) {
    static uint8_t zero[16016];
    for (int t = 0; t < MTK_TABLES_N; t++) {
        for (int restore = 0; restore < 2; restore++) {
            char p[256];
            snprintf(p, sizeof p, "%s/%s-%s.bin", dir, MTK_TRACE[t].name, restore ? "restore" : "trim");
            size_t n = mtk_trace_packet(t, restore ? MTK_TRACE[t].orig : zero);
            FILE *f = fopen(p, "wb");
            if (!f || fwrite(mtk_tx, 1, n, f) != n) return 1;
            fclose(f);
        }
    }
    /* the ICD filter frames mtk_enable_icd sends, in order (seq 1...) */
    uint8_t seq = 1;
    for (size_t r = 0; r < sizeof MTK_RECORD_RANGES / sizeof MTK_RECORD_RANGES[0]; r++) {
        char p[256];
        snprintf(p, sizeof p, "%s/icd-record-%zu.bin", dir, r);
        size_t n = mtk_set_filter(seq++, 1, MTK_RECORD_RANGES[r][0], MTK_RECORD_RANGES[r][1], MTK_RECORDS,
                                  (int)(sizeof MTK_RECORDS / sizeof MTK_RECORDS[0]));
        FILE *f = fopen(p, "wb");
        if (!f || fwrite(mtk_tx, 1, n, f) != n) return 1;
        fclose(f);
    }
    const char *names[] = { "connect", "disconnect", "version" };
    for (int i = 0; i < 3; i++) {
        size_t n = i == 0 ? mtk_host(0x2E, MTK_CONNECT, 4) : i == 1 ? mtk_host(0x2F, MTK_DISCONNECT, 4) : mtk_icd(1, 0, NULL, 0);
        char p[256];
        snprintf(p, sizeof p, "%s/%s.bin", dir, names[i]);
        FILE *f = fopen(p, "wb");
        if (!f || fwrite(mtk_tx, 1, n, f) != n) return 1;
        fclose(f);
    }
    return 0;
}

/* Offline replay of a saved debug-port capture: prints the stats every `every_ms` of
 * stream time at `rate` bytes/s. */
static int mtk_replay(const char *path, long rate, long every_ms, int log_code) {
    FILE *f = fopen(path, "rb");
    if (!f || !mtk_init()) return 1;
    static char out[65536];
    uint8_t buf[65536];
    size_t k;
    long fed = 0, next = rate * every_ms / 1000;
    while ((k = fread(buf, 1, sizeof buf, f)) > 0) {
        mtk_feed(buf, k);
        fed += (long)k;
        usleep((useconds_t)(k * 1000000 / (size_t)rate));
        if (fed >= next) {
            next += rate * every_ms / 1000;
            int n = write_stats_mtk(out, sizeof out, 1);
            if (n > 0) fwrite(out, 1, (size_t)n, stdout);
        }
    }
    fclose(f);
    if (log_code >= 0) {
        int n = mtk_log_json(out, sizeof out, (uint16_t)log_code);
        if (n > 0) fwrite(out, 1, (size_t)n, stdout);
    }
    fprintf(stderr, "replay: %ld bytes, %ld frames, %ld resyncs, %ld records, %ld events, firmware %s, dump %d\n",
            mtk_bytes, mtk_frames, mtk_resyncs, mtk_codes_seen[0], mtk_codes_seen[1], mtk_tf.firmware, mtk_tf.dumped);
    return 0;
}
