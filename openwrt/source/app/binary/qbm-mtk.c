/* LTE's TX-antenna count comes from the MIB (0x7104 / 0x700C); hold it per
 * PCI+EARFCN so the carrier keeps it across windows and reconfigurations. */
struct mtk_lte_tx { uint32_t arfcn; int pci, tx; long at; };
static struct mtk_lte_tx mtk_lte_tx[16];

static void mtk_lte_tx_put(uint32_t arfcn, int pci, int tx, long now) {
    int slot = -1, oldest = 0;
    for (int i = 0; i < 16; i++) {
        if (mtk_lte_tx[i].tx && mtk_lte_tx[i].arfcn == arfcn && mtk_lte_tx[i].pci == pci) {
            /* hold the highest count seen for this cell; a later MIB/SIB or a
             * lower-port reconfiguration must not shrink it */
            if (tx > mtk_lte_tx[i].tx) mtk_lte_tx[i].tx = tx;
            mtk_lte_tx[i].at = now;
            return;
        }
        if (!mtk_lte_tx[i].tx) { if (slot < 0) slot = i; }
        else if (mtk_lte_tx[i].at < mtk_lte_tx[oldest].at) oldest = i;
    }
    if (slot < 0) slot = oldest;
    mtk_lte_tx[slot].arfcn = arfcn; mtk_lte_tx[slot].pci = pci;
    mtk_lte_tx[slot].tx = tx; mtk_lte_tx[slot].at = now;
}

static int mtk_lte_tx_get(uint32_t arfcn, int pci) {
    for (int i = 0; i < 16; i++)
        if (mtk_lte_tx[i].tx && mtk_lte_tx[i].arfcn == arfcn && mtk_lte_tx[i].pci == pci)
            return mtk_lte_tx[i].tx;
    return 0;
}

/* LTE RRC: the SCell reconfiguration carries antennaPortsCount for the SCell
 * (MIB only covers the PCell). lte_csi.c keeps the cell's PCI/EARFCN +1 to
 * tell "absent" from 0, and exposes the state in its callback context. */
static struct lte_state mtk_lte_rrc;

static void mtk_lte_rrc_emit(void *ctx, int index, const struct lte_summary *sum) {
    struct lte_state *st = ctx;
    (void)sum;
    if (index < 0 || index >= LTE_MAX_CELLS) return;
    struct lte_cell *c = &st->cells[index];
    if (c->pci > 0 && c->frequency > 0 && c->crs_ports > 0)
        mtk_lte_tx_put((uint32_t)(c->frequency - 1), (int)(c->pci - 1), c->crs_ports, now_ms());
}

