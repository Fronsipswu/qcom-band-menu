/*
 * qbm-mtk.c: the MediaTek (Fibocom FM350) backend of qbm-diagd on OpenWrt, included by
 * qbm-diagd-usb.c. The modem's USB debug port (interface 09) carries MediaTek's logging
 * protocol instead of Qualcomm DIAG:
 *
 *   USB mux frame: u32 0x10EFCAAC, u32 payload bytes, u32 channel/flags, u32 XOR of the
 *     three, payload. Channel 0x10 is the main logging channel; 0x9610/0x9A10 carry L1
 *     traces (off once the trace filters are trimmed).
 *   DHL record on channel 0x10: u8 kind, u24 total bytes (with this header). Kind 0x11 is an
 *     ICD log record (u16 code at 6, payload from 0x14), 0x20 an ICD event (payload from
 *     0x10), 0x12 an ICD command reply, 0x15 a trace (the trace filter tables are dumped as
 *     traces on connect), 0x13/0x17 others.
 *   Host commands: one mux frame on flags 0xA010 with the DHL sync record, then a kind-0x16
 *     host command (native connect/disconnect, trace filter setters) or a kind-0x12 ICD
 *     command (query version, set ICD filter).
 *
 * ICD logging is off by default: after connect this backend enables exactly the record
 * codes it decodes (every record range is written, so other codes go off) and the NR RRC
 * event 0x960D. Records are decoded with the firmware's own ICD layouts
 * (qbm_mtk_tables.h, generated by tools/gen_mtk_tables.py) and aggregated into the same
 * stats JSON the Qualcomm backend writes.
 *
 * Trace filters (-mtk-trim): the default stream is ~4.4 MB/s of DHL traces. Five trace
 * filter tables set to zero cut it to ~36 KB/s with ICD unaffected (live-tested on firmware
 * 81600.0000.00.19.15.13). Each setter is saved to the modem's NVRAM, so this backend writes
 * only tables that differ: the modem dumps all five on connect while they are not trimmed,
 * and a trimmed modem sends no dump at all. The table sizes are firmware-specific (the modem
 * copies what it is sent into a fixed buffer), so nothing is written unless the firmware is
 * the one these sizes were verified on, and a dumped table must have the expected size.
 * "Restore MTK DIAG profile" writes the modem's original tables back.
 *
 * NR bandwidth is the active BWP's, from the physical configuration log (its RB count when
 * that is a whole channel: SCell configurations leave the bandwidth index at 0).
 */

