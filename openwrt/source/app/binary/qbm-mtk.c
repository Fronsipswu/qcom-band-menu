/* JSON into out[cap] at offset o (keeps counting past cap, like write_stats's PUT) */
#define MPUT(...) do { int k_ = snprintf(out + o, o < cap ? cap - o : 0, __VA_ARGS__); if (k_ > 0) o += (size_t)k_; } while (0)

static const uint8_t MTK_SYNC[8] = { 0x17, 0x08, 0x00, 0x00, 0xAC, 0xDB, 0xCF, 0xE5 };

/* ── ICD layouts: a walker over the generated tables ─────────────────────── */

/* One decoded struct: the record's bits, the struct's table and its first bit. */
struct mtk_node { const uint8_t *p; uint32_t nbits; uint16_t table; uint32_t base; };

static int mtk_get_bits(const struct mtk_node *n, uint32_t pos, int width, int is_signed, int64_t *out) {
    if (width <= 0 || width > 64 || (uint64_t)pos + (uint64_t)width > n->nbits) return 0;
    uint64_t v = 0;
    for (int i = 0; i < width;) {
        uint32_t at = pos + (uint32_t)i;
        int take = 8 - (int)(at & 7);
        if (take > width - i) take = width - i;
        uint64_t chunk = (n->p[at >> 3] >> (at & 7)) & ((1u << take) - 1);
        v |= chunk << i;
        i += take;
    }
    if (is_signed && width < 64 && (v >> (width - 1)) & 1) v |= ~0ULL << width;
    *out = (int64_t)v;
    return 1;
}

static const char *mtk_name(const struct mtk_row *r) { return MTK_NAMES + r->name; }

static int mtk_row_in(uint16_t table, const char *name) {
    const struct mtk_table *t = &MTK_TABLES[table];
    for (int i = 0; i < t->rows; i++)
        if (!strcmp(mtk_name(&MTK_ROWS[t->first + i]), name)) return t->first + i;
    return -1;
}

static int mtk_prim_width(const struct mtk_row *r, long count) {
    if (r->len != 0xFFFFFFFFu) return (int)(r->len / (uint32_t)(count > 0 ? count : 1));
    return r->prim == 1 || r->prim == 5 ? 8 : r->prim == 2 || r->prim == 6 ? 16 : 32;
}

static int mtk_signed(const struct mtk_row *r) { return r->prim >= 5; }

/* The element count of row r in the struct at n; -1 when its count field is unreadable. */
static long mtk_count(const struct mtk_node *n, const struct mtk_row *r) {
    if (r->count != 0xFFFF) return r->count;
    const struct mtk_row *c = &MTK_ROWS[MTK_TABLES[n->table].first + r->ref];
    int64_t v;
    if (!c->prim || !mtk_get_bits(n, n->base + c->off, mtk_prim_width(c, c->count == 0xFFFF ? 1 : c->count), 0, &v))
        return -1;
    return v < 0 || v > 4096 ? -1 : (long)v;
}

static long mtk_table_bits(uint16_t table);

/* Bits from one struct item to the next: fixed by the row, else the type's size, else -1
 * (it ends in a VAR field: walk it). */
static long mtk_stride(const struct mtk_row *r, long count) {
    if (r->len != 0xFFFFFFFFu && count > 0) return (long)(r->len / (uint32_t)count);
    return mtk_table_bits(r->sub);
}

static long mtk_end(const struct mtk_node *n, int depth);

/* Positions of row r's struct items in n (up to max); returns how many, -1 on error. */
static int mtk_item_nodes(const struct mtk_node *n, const struct mtk_row *r, struct mtk_node *out, int max, long *end) {
    long count = mtk_count(n, r);
    if (count < 0) return -1;
    long stride = mtk_stride(r, count);
    uint32_t pos = n->base + r->off;
    int k = 0;
    for (long i = 0; i < count; i++) {
        struct mtk_node item = { n->p, n->nbits, r->sub, pos };
        if (k < max) out[k++] = item;
        if (stride >= 0) pos += (uint32_t)stride;
        else {
            long e = mtk_end(&item, 0);
            if (e < 0) return -1;
            pos = (uint32_t)e;
        }
        if (pos > n->nbits) return -1;
    }
    if (end) *end = pos;
    return k;
}

/* The end bit of the struct at n (its last field's end), -1 on error. */
static long mtk_end(const struct mtk_node *n, int depth) {
    if (depth > 12) return -1;
    const struct mtk_table *t = &MTK_TABLES[n->table];
    long end = n->base;
    for (int i = 0; i < t->rows; i++) {
        const struct mtk_row *r = &MTK_ROWS[t->first + i];
        long count = mtk_count(n, r), e;
        if (count < 0) return -1;
        if (r->prim) e = (long)(n->base + r->off) + count * mtk_prim_width(r, count);
        else {
            long stride = mtk_stride(r, count);
            if (stride >= 0) e = (long)(n->base + r->off) + count * stride;
            else if (mtk_item_nodes(n, r, NULL, 0, &e) < 0) return -1;
        }
        if (e > end) end = e;
    }
    return end <= (long)n->nbits ? end : -1;
}

static long mtk_table_bits(uint16_t table) {
    static int32_t cache[sizeof MTK_TABLES / sizeof MTK_TABLES[0]];
    static uint8_t done[sizeof MTK_TABLES / sizeof MTK_TABLES[0]];
    if (done[table]) return cache[table];
    const struct mtk_table *t = &MTK_TABLES[table];
    long size = 0;
    for (int i = 0; i < t->rows && size >= 0; i++) {
        const struct mtk_row *r = &MTK_ROWS[t->first + i];
        if (r->len == 0xFFFFFFFFu) size = -1;
        else if ((long)(r->off + r->len) > size) size = (long)(r->off + r->len);
    }
    done[table] = 1;
    cache[table] = (int32_t)size;
    return size;
}

/* Field `name` of the struct at n: its first value (prim). 0 when absent or unreadable. */
static int mtk_get(const struct mtk_node *n, const char *name, int64_t *v) {
    int ri = n ? mtk_row_in(n->table, name) : -1;
    if (ri < 0) return 0;
    const struct mtk_row *r = &MTK_ROWS[ri];
    long count = mtk_count(n, r);
    if (!r->prim || count < 1) return 0;
    return mtk_get_bits(n, n->base + r->off, mtk_prim_width(r, count), mtk_signed(r), v);
}

static double mtk_getd(const struct mtk_node *n, const char *name, int *ok) {
    int64_t v;
    *ok = mtk_get(n, name, &v);
    return *ok ? (double)v : 0;
}

/* Values of prim array `name` (up to max); returns how many, 0 when absent. */
static int mtk_list(const struct mtk_node *n, const char *name, int64_t *v, int max) {
    int ri = mtk_row_in(n->table, name);
    if (ri < 0) return 0;
    const struct mtk_row *r = &MTK_ROWS[ri];
    long count = mtk_count(n, r);
    if (!r->prim || count < 0) return 0;
    int w = mtk_prim_width(r, count), k = 0;
    for (long i = 0; i < count && k < max; i++)
        if (!mtk_get_bits(n, n->base + r->off + (uint32_t)(i * w), w, mtk_signed(r), &v[k++])) return k - 1;
    return k;
}

/* The struct items of field `name` (one for a single struct; up to max). */
static int mtk_items(const struct mtk_node *n, const char *name, struct mtk_node *out, int max) {
    int ri = n ? mtk_row_in(n->table, name) : -1;
    if (ri < 0 || MTK_ROWS[ri].prim) return 0;
    int k = mtk_item_nodes(n, &MTK_ROWS[ri], out, max, NULL);
    return k < 0 ? 0 : k;
}

static int mtk_item(const struct mtk_node *n, const char *name, struct mtk_node *out) {
    return mtk_items(n, name, out, 1) == 1;
}

/* The root struct of a log record: payload[0] is its version. */
static int mtk_open_record(uint16_t code, const uint8_t *payload, size_t n, struct mtk_node *root) {
    if (n < 1 || n > 1u << 24) return 0;
    for (size_t i = 0; i < sizeof MTK_VERSIONS / sizeof MTK_VERSIONS[0]; i++) {
        if (MTK_VERSIONS[i].code == code && MTK_VERSIONS[i].version == payload[0]) {
            *root = (struct mtk_node){ payload, (uint32_t)(n * 8), MTK_VERSIONS[i].table, 8 };
            return 1;
        }
    }
    return 0;
}

/* ── Host commands ───────────────────────────────────────────────────────── */

static uint8_t mtk_tx[2 + 16 + 8 + 12 + 20000];

/* One host->modem frame around the DHL sync record and `body`; returns its length. */
static size_t mtk_frame(const uint8_t *body, size_t n) {
    uint32_t len = (uint32_t)(sizeof MTK_SYNC + n);
    put32(mtk_tx, MTK_MAGIC);
    put32(mtk_tx + 4, len);
    put32(mtk_tx + 8, MTK_CMD_FLAGS);
    put32(mtk_tx + 12, MTK_MAGIC ^ len ^ MTK_CMD_FLAGS);
    memcpy(mtk_tx + 16, MTK_SYNC, sizeof MTK_SYNC);
    memcpy(mtk_tx + 24, body, n);
    return 24 + n;
}

/* A kind-0x16 host command: 00 cmd 00 cmd, params, BD DB, u16 sum of what precedes it. */
static size_t mtk_host(uint8_t cmd, const uint8_t *params, size_t n) {
    static uint8_t b[20000];
    if (n + 12 > sizeof b) return 0;
    uint8_t *c = b + 4;
    c[0] = 0; c[1] = cmd; c[2] = 0; c[3] = cmd;
    if (n) memcpy(c + 4, params, n);
    c[4 + n] = 0xBD; c[5 + n] = 0xDB;
    uint32_t sum = 0;
    for (size_t i = 0; i < n + 4; i++) sum += c[i];
    put16(c + 6 + n, (uint16_t)sum);
    size_t total = n + 12;
    b[0] = 0x16; b[1] = (uint8_t)total; b[2] = (uint8_t)(total >> 8); b[3] = (uint8_t)(total >> 16);
    return mtk_frame(b, total);
}

/* A kind-0x12 ICD command: u8 0x12, u24 length, u8 0, u8 seq, u16 cmd, u32 check, payload. */
static size_t mtk_icd(uint16_t cmd, uint8_t seq, const uint8_t *payload, size_t n) {
    static uint8_t b[12 + 1100];
    if (n > sizeof b - 12) return 0;
    uint32_t w0 = (uint32_t)(12 + n) << 8 | MTK_ICD_REPLY, w1 = (uint32_t)cmd << 16 | (uint32_t)seq << 8;
    put32(b, w0); put32(b + 4, w1); put32(b + 8, w0 + w1);
    if (n) memcpy(b + 12, payload, n);
    return mtk_frame(b, 12 + n);
}

